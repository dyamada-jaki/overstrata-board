import { expect, test, type Page } from '@playwright/test'
import { setCount } from './counts.ts'

const cell = (page: Page, x: number, y: number) => page.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })

test('塞がれた斜めの目安は倒れた駒を通過して変化し、範囲外へも自由に移動して解除できる', async ({ page }, testInfo) => {
  await page.goto('/')
  await setCount(page, '味方の数', 2)
  await setCount(page, '敵の数', 1)
  await button(page, '駒を用意する').click()
  for (const [name, x, y] of [['味方1', 1, 1], ['味方2', 2, 1], ['敵1', 1, 2]] as const) {
    await page.getByRole('button', { name: new RegExp(`^未配置 ${name}（`) }).click()
    await cell(page, x, y).click()
  }
  await cell(page, 1, 1).click()
  await button(page, '設定').click()
  for (let i = 0; i < 4; i += 1) await button(page, '味方1の移動力を減らす').click()
  await button(page, '閉じる').click()
  await button(page, '確定').click()
  await cell(page, 1, 1).click()
  await expect(page.locator('.board-cell-range')).toHaveCount(0)
  await cell(page, 1, 2).click()
  await button(page, '設定').click()
  await button(page, '倒れた状態にする').click()
  await button(page, '閉じる').click()
  await expect(page.locator('.board-cell-range')).toHaveCount(0)
  await cell(page, 1, 1).click()
  await expect(cell(page, 2, 2)).toHaveAccessibleName('マス (2, 2) 移動範囲')
  await expect(page.locator('.board-cell-range')).toHaveCount(1)
  await expect(cell(page, 1, 2)).not.toHaveClass(/board-cell-range/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await testInfo.attach('片方の脇が倒れた駒なら斜めに到達できる', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await cell(page, 1, 2).click()
  await button(page, '設定').click()
  await button(page, '通常に戻す').click()
  await button(page, '閉じる').click()
  await cell(page, 1, 1).click()
  await expect(page.locator('.board-cell-range')).toHaveCount(0)
  await cell(page, 2, 2).click()
  await expect(cell(page, 2, 2)).toHaveAccessibleName('マス (2, 2) 味方1（味方・移動力1）')
  await expect(page.getByRole('button', { pressed: true })).toHaveCount(0)
  await expect(page.locator('.board-cell-range')).toHaveCount(0)
})
