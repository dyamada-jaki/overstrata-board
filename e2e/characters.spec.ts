import { expect, test } from '@playwright/test'

test('キャラ選択・別キャラ切替・範囲内外への移動・全解除を一連で操作できる', async ({ page }, testInfo) => {
  await page.goto('/')
  const character = (name: string) => page.getByRole('button', { name: new RegExp(` ${name} `) })
  const cell = (x: number, y: number) => page.getByRole('button', { name: `マス (${x}, ${y})`, exact: true })
  const range = page.locator('button[aria-description="移動範囲"]')
  const selected = page.getByRole('button', { pressed: true })
  const characters = page.getByRole('button', { name: / (味方|敵)[12] / })
  for (const [name, number] of [['味方1', '1'], ['味方2', '2'], ['敵1', '1'], ['敵2', '2']]) {
    await expect(character(name)).toHaveText(number)
    await expect(character(name).locator('span')).toHaveCSS('color', 'rgb(255, 255, 255)')
    await expect(character(name).locator('span')).toHaveCSS('background-color',
      name.startsWith('味方') ? 'rgb(29, 78, 216)' : 'rgb(185, 28, 28)')
  }
  const initial = await characters.allTextContents()
  const placements = await characters.evaluateAll((elements) => elements.map((element) => element.getAttribute('aria-label')))
  await cell(1, 1).click()
  await expect(selected).toHaveCount(1)
  await character('味方1').click()
  await expect(selected).toHaveCount(1)
  await expect(character('味方1')).toHaveAttribute('aria-pressed', 'true')
  await expect(cell(3, 3)).toHaveAccessibleDescription('移動範囲')
  await expect(character('敵1')).not.toHaveAccessibleDescription('移動範囲')
  await testInfo.attach('キャラ選択と移動範囲', { body: await page.screenshot(), contentType: 'image/png' })
  await character('敵1').click()
  expect(await characters.allTextContents()).toEqual(initial)
  expect(await characters.evaluateAll((elements) => elements.map((element) => element.getAttribute('aria-label')))).toEqual(placements)
  await expect(selected).toHaveCount(1)
  await expect(character('敵1')).toHaveAttribute('aria-pressed', 'true')
  await expect(cell(4, 7)).toHaveAccessibleDescription('移動範囲')
  await expect(cell(3, 9)).not.toHaveAccessibleDescription('移動範囲')
  await cell(4, 7).click()
  await expect(character('敵1')).toHaveAccessibleName('マス (4, 7) 敵1 敵 中装 移動力4')
  await expect(selected).toHaveCount(0)
  await expect(range).toHaveCount(0)
  await character('味方1').click()
  await expect(cell(10, 1)).not.toHaveAccessibleDescription('移動範囲')
  await cell(10, 1).click()
  await expect(character('味方1')).toHaveAccessibleName('マス (10, 1) 味方1 味方 軽装 移動力5')
  await expect(selected).toHaveCount(0)
  await expect(range).toHaveCount(0)
  await character('味方1').click()
  await expect(selected).toHaveCount(1)
  await character('味方1').click()
  await expect(selected).toHaveCount(0)
  await expect(range).toHaveCount(0)
})
