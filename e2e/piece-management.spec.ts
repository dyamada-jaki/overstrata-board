import { expect, test, type Page } from '@playwright/test'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const cell = (page: Page, x: number, y: number) => page.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const token = (page: Page, name: string) => page.getByRole('button', { name: new RegExp(`(?:^未配置 | )${name}（`) })
// #45 で選択中の駒の設定はポップアップへ移った。「設定」で開き、背後を操作する前に「×」で閉じる。
const openSettings = (page: Page) => page.getByRole('button', { name: '設定', exact: true }).click()
const closeSettings = async (page: Page) => {
  await page.getByRole('button', { name: '閉じる', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
async function add(page: Page) {
  await button(page, '駒を増やす').click()
  await page.getByRole('textbox', { name: '敵の追加数' }).fill('1')
  await button(page, '追加する').click()
}

test('戦闘途中の追加→配置後の設定→再追加→まとめて確定→移動と削除を使える', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: '味方の数' }).fill('1')
  await button(page, '駒を用意する').click()
  await token(page, '味方1').click()
  await cell(page, 1, 1).click()
  await button(page, '確定').click()
  await token(page, '味方1').click()
  await add(page)
  await expect(cell(page, 1, 1)).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('group', { name: /の移動力$/ })).toHaveCount(0)
  await expect(button(page, '追加分を確定')).toBeDisabled()
  await token(page, '敵1').click()
  await openSettings(page)
  await button(page, '敵1の移動力を減らす').click()
  await closeSettings(page)
  await cell(page, 2, 1).click()
  await token(page, '敵1').click()
  await openSettings(page)
  await button(page, '敵1の移動力を減らす').click()
  await expect(cell(page, 5, 1)).toHaveAccessibleName('マス (5, 1) 移動範囲')
  await expect(cell(page, 6, 1)).toHaveAccessibleName('マス (6, 1)')
  await closeSettings(page)
  await expect(button(page, '追加分を確定')).toBeEnabled()
  await add(page)
  await expect(cell(page, 2, 1)).toHaveAccessibleName('マス (2, 1) 敵1（敵・移動力3）')
  await expect(button(page, '追加分を確定')).toBeDisabled()
  await token(page, '敵2').click()
  await cell(page, 3, 1).click()
  await token(page, '敵1').click()
  await testInfo.attach('追加分の設定と配置', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  await button(page, '追加分を確定').click()
  await expect(page.getByRole('button', { pressed: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: / 移動範囲$/ })).toHaveCount(0)
  await token(page, '敵1').click()
  await openSettings(page)
  await expect(page.getByRole('group', { name: /の移動力$/ })).toHaveCount(0)
  await closeSettings(page)
  await cell(page, 10, 10).click()
  await expect(cell(page, 10, 10)).toHaveAccessibleName('マス (10, 10) 敵1（敵・移動力3）')
  await token(page, '敵1').click()
  await openSettings(page)
  await button(page, 'この駒を削除').click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('敵1を削除しますか？')
  await expect(button(page, 'キャンセル')).toBeFocused()
  expect(await dialog.evaluate((el) => el.matches(':modal'))).toBe(true)
  await page.keyboard.press('Shift+Tab')
  await expect(button(page, '削除する')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(button(page, 'キャンセル')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(token(page, '敵1')).toHaveAttribute('aria-pressed', 'true')
  await expect(button(page, 'この駒を削除')).toBeFocused()
  await button(page, 'この駒を削除').click()
  await button(page, '削除する').click()
  await expect(cell(page, 10, 10)).toHaveAccessibleName('マス (10, 10)')
  await expect(cell(page, 1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5）')
  await expect(cell(page, 3, 1)).toHaveAccessibleName('マス (3, 1) 敵2（敵・移動力5）')
  await expect(page.locator('body')).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})

test('追加取消と未配置削除は番号を消費/再利用せず、追加分全削除で準備が終わる', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: '敵の数' }).fill('1')
  await button(page, '駒を用意する').click()
  await token(page, '敵1').click()
  await cell(page, 1, 1).click()
  await button(page, '確定').click()
  await button(page, '駒を増やす').click()
  await page.getByRole('textbox', { name: '敵の追加数' }).fill('2')
  await button(page, 'キャンセル').click()
  await add(page)
  await expect(token(page, '敵2')).toBeVisible()
  await token(page, '敵2').click()
  await openSettings(page)
  await button(page, 'この駒を削除').click()
  await button(page, 'キャンセル').click()
  await expect(token(page, '敵2')).toHaveAttribute('aria-pressed', 'true')
  await button(page, 'この駒を削除').click()
  await button(page, '削除する').click()
  await expect(button(page, '追加分を確定')).toHaveCount(0)
  await expect(page.getByRole('region', { name: '戦闘中' })).toBeVisible()
  await add(page)
  await expect(token(page, '敵3')).toBeVisible()
  await expect(cell(page, 1, 1)).toHaveAccessibleName('マス (1, 1) 敵1（敵・移動力5）')
})
