import { fireEvent, render, screen, within } from '@testing-library/react'
import App from './App.tsx'
import { clickWithSettings as click, openSettings, selectAndOpen } from './test/piece-settings.ts'

const cell = (x: number, y: number) => screen.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const token = (name: string) => screen.getByRole('button', { name: new RegExp(`(?:^未配置 | )${name}（`) })
const pressed = () => screen.queryAllByRole('button', { pressed: true })
const range = () => screen.queryAllByRole('button', { name: / 移動範囲$/ }).map((el) => el.getAttribute('aria-label'))
const occupants = () => screen.queryAllByRole('button', { name: /^マス .*（/ }).map((el) => el.getAttribute('aria-label'))
const setting = (name: string) => { openSettings(); return screen.getByRole('group', { name: `${name}の移動力` }) }
const settings = () => screen.queryAllByRole('group', { name: /の移動力$/ })
const minus = (name: string) => within(setting(name)).getByRole('button', { name: `${name}の移動力を減らす` })
const plus = (name: string) => within(setting(name)).getByRole('button', { name: `${name}の移動力を増やす` })
const value = (name: string) => within(setting(name)).getByRole('status')
const times = (button: () => HTMLElement, count: number) => {
  for (let i = 0; i < count; i += 1) fireEvent.click(button())
}
function prepare(ally: string, enemy: string) {
  fireEvent.change(screen.getByRole('textbox', { name: '味方の数' }), { target: { value: ally } })
  fireEvent.change(screen.getByRole('textbox', { name: '敵の数' }), { target: { value: enemy } })
  click('駒を用意する')
}
function place(name: string, x: number, y: number) {
  selectAndOpen(token(name))
  selectAndOpen(cell(x, y))
}

describe('準備中の駒ごとの移動力（#37）', () => {
  it('選んだ駒の欄に初期値5を表示専用で出し、＋/−は対象の駒だけに反映する', () => {
    render(<App />)
    prepare('2', '1')
    expect(screen.getByText(/移動力の初期値は5マス/)).toBeVisible()
    place('敵1', 5, 5)
    expect(settings()).toEqual([])
    selectAndOpen(token('味方1'))
    expect(settings()).toHaveLength(1)
    expect(value('味方1')).toHaveTextContent(/^5$/)
    expect(within(setting('味方1')).queryByRole('textbox')).not.toBeInTheDocument()
    expect(within(setting('味方1')).queryByRole('spinbutton')).not.toBeInTheDocument()
    expect(within(setting('味方1')).getByText('1')).toBeVisible() // 陣営色の丸の番号
    fireEvent.click(plus('味方1'))
    expect(value('味方1')).toHaveTextContent(/^6$/)
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力6）')
    expect(token('味方2')).toHaveAccessibleName('未配置 味方2（味方・移動力5）')
    expect(cell(5, 5)).toHaveAccessibleName('マス (5, 5) 敵1（敵・移動力5）')
    fireEvent.click(minus('味方1'))
    fireEvent.click(minus('味方1'))
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力4）')
    expect(token('味方2')).toHaveAccessibleName('未配置 味方2（味方・移動力5）')
  })

  it('−/＋は1ずつで0と9を設定でき、0の−と9の＋は押せない', () => {
    render(<App />)
    prepare('1', '0')
    selectAndOpen(token('味方1'))
    expect(minus('味方1')).toBeEnabled()
    expect(plus('味方1')).toBeEnabled()
    times(() => minus('味方1'), 4)
    expect(value('味方1')).toHaveTextContent(/^1$/)
    expect(minus('味方1')).toBeEnabled()
    fireEvent.click(minus('味方1'))
    expect(value('味方1')).toHaveTextContent(/^0$/)
    expect(minus('味方1')).toBeDisabled()
    expect(plus('味方1')).toBeEnabled()
    times(() => plus('味方1'), 8)
    expect(value('味方1')).toHaveTextContent(/^8$/)
    expect(plus('味方1')).toBeEnabled()
    fireEvent.click(plus('味方1'))
    expect(value('味方1')).toHaveTextContent(/^9$/)
    expect(plus('味方1')).toBeDisabled()
    expect(minus('味方1')).toBeEnabled()
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力9）')
  })

  it('配置済みで選択中の駒は、選択と位置を保ったまま範囲をすぐ更新し、他の駒のマスは含めない', () => {
    render(<App />)
    prepare('1', '1')
    place('味方1', 1, 1)
    place('敵1', 2, 1)
    selectAndOpen(cell(1, 1))
    expect(cell(6, 1)).toHaveAccessibleName('マス (6, 1) 移動範囲')
    expect(cell(7, 1)).toHaveAccessibleName('マス (7, 1)')
    const before = occupants()
    fireEvent.click(plus('味方1'))
    expect(cell(7, 1)).toHaveAccessibleName('マス (7, 1) 移動範囲')
    expect(cell(8, 1)).toHaveAccessibleName('マス (8, 1)')
    expect(pressed()).toEqual([cell(1, 1)])
    times(() => minus('味方1'), 2)
    expect(cell(5, 1)).toHaveAccessibleName('マス (5, 1) 移動範囲')
    expect(cell(6, 1)).toHaveAccessibleName('マス (6, 1)')
    // 斜めに3は距離4、右へ4・下へ3は距離5（spec.md 3.1）。
    expect(cell(4, 4)).toHaveAccessibleName('マス (4, 4) 移動範囲')
    expect(cell(5, 4)).toHaveAccessibleName('マス (5, 4)')
    expect(range()).not.toContain('マス (2, 1) 敵1（敵・移動力5） 移動範囲')
    expect(cell(2, 1)).toHaveAccessibleName('マス (2, 1) 敵1（敵・移動力5）')
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力4）')
    expect(pressed()).toEqual([cell(1, 1)])
    expect(occupants()).toEqual(before.map((label) => label!.replace('味方・移動力5', '味方・移動力4')))
  })

  it('移動力0では範囲が出なくても選択・移動でき、範囲外の空きマスへ動かせる', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    selectAndOpen(cell(1, 1))
    times(() => minus('味方1'), 5)
    expect(value('味方1')).toHaveTextContent(/^0$/)
    expect(range()).toEqual([])
    expect(pressed()).toEqual([cell(1, 1)])
    selectAndOpen(cell(10, 10))
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 味方1（味方・移動力0）')
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1)')
    expect(settings()).toEqual([])
    selectAndOpen(cell(10, 10))
    expect(pressed()).toEqual([cell(10, 10)])
    expect(value('味方1')).toHaveTextContent(/^0$/)
  })

  it('欄は選択中の駒を示し、選択の切替・解除・マス選択に従う', () => {
    render(<App />)
    prepare('1', '1')
    selectAndOpen(token('味方1'))
    times(() => plus('味方1'), 2)
    selectAndOpen(token('敵1'))
    expect(settings()).toHaveLength(1)
    expect(value('敵1')).toHaveTextContent(/^5$/)
    selectAndOpen(token('味方1'))
    expect(value('味方1')).toHaveTextContent(/^7$/)
    selectAndOpen(token('味方1'))
    expect(settings()).toEqual([])
    selectAndOpen(cell(3, 3))
    expect(settings()).toEqual([])
  })

  it('未配置で変えた値を配置・確定で引き継ぎ、確定後は変更欄を出さず設定値で範囲を出す', () => {
    render(<App />)
    prepare('1', '0')
    selectAndOpen(token('味方1'))
    times(() => minus('味方1'), 2)
    selectAndOpen(cell(1, 1))
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力3）')
    selectAndOpen(cell(1, 1))
    expect(value('味方1')).toHaveTextContent(/^3$/)
    click('確定')
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力3）')
    selectAndOpen(cell(1, 1))
    expect(pressed()).toEqual([cell(1, 1)])
    expect(settings()).toEqual([])
    expect(screen.queryByRole('button', { name: /の移動力を(?:増や|減ら)す$/ })).not.toBeInTheDocument()
    expect(cell(4, 1)).toHaveAccessibleName('マス (4, 1) 移動範囲')
    expect(cell(5, 1)).toHaveAccessibleName('マス (5, 1)')
  })

  it('やり直しの取消では変えた値を保ち、実行後に用意した駒は5から始まる', () => {
    render(<App />)
    prepare('1', '0')
    selectAndOpen(token('味方1'))
    times(() => plus('味方1'), 3)
    click('準備をやり直す')
    click('キャンセル')
    expect(value('味方1')).toHaveTextContent(/^8$/)
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力8）')
    click('準備をやり直す')
    click('やり直す')
    prepare('1', '0')
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力5）')
    selectAndOpen(token('味方1'))
    expect(value('味方1')).toHaveTextContent(/^5$/)
  })

  it('新しい戦闘の取消では確定した値を保ち、実行後に用意した駒は5から始まる', () => {
    render(<App />)
    prepare('0', '1')
    selectAndOpen(token('敵1'))
    times(() => minus('敵1'), 5)
    selectAndOpen(cell(5, 5))
    click('確定')
    click('新しい戦闘を始める')
    click('キャンセル')
    expect(cell(5, 5)).toHaveAccessibleName('マス (5, 5) 敵1（敵・移動力0）')
    click('新しい戦闘を始める')
    click('始める')
    prepare('0', '1')
    expect(token('敵1')).toHaveAccessibleName('未配置 敵1（敵・移動力5）')
  })
})
