import { fireEvent, render, screen, within } from '@testing-library/react'
import App from './App.tsx'
import { clickWithSettings as click, openSettings, selectAndOpen } from './test/piece-settings.ts'

const cell = (x: number, y: number) => screen.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const token = (name: string) => {
  const group = screen.queryByRole('group', { name: '未配置の駒' })
  return (group && within(group).queryByRole('button', { name: new RegExp(`^未配置 ${name}（`) }))
    || screen.getByRole('button', { name: new RegExp(`(?:^未配置 | )${name}（`) })
}
const input = (name: string, value: string) => fireEvent.change(screen.getByRole('textbox', { name }), { target: { value } })
const form = () => screen.getByRole('group', { name: '駒の追加数' })
const pending = () => within(screen.getByRole('group', { name: '未配置の駒' }))
const pressed = () => screen.queryAllByRole('button', { pressed: true })
const range = () => screen.queryAllByRole('button', { name: / 移動範囲$/ })
const settings = () => screen.queryAllByRole('group', { name: /の移動力$/ })
const value = (name: string) => { openSettings(); return within(screen.getByRole('group', { name: `${name}の移動力` })).getByRole('status') }
function prepare(ally = '0', enemy = '1') {
  input('味方の数', ally)
  input('敵の数', enemy)
  click('駒を用意する')
}
function add(ally = '0', enemy = '1') {
  click('駒を増やす')
  input('味方の追加数', ally)
  input('敵の追加数', enemy)
  click('追加する')
  expect(screen.queryByRole('group', { name: '駒の追加数' })).not.toBeInTheDocument()
}
function place(name: string, x: number, y: number) {
  selectAndOpen(token(name))
  selectAndOpen(cell(x, y))
}
function remove(name: string) {
  selectAndOpen(token(name))
  fireEvent.click(screen.getByText('この駒を削除', { selector: 'button' }))
  const dialog = screen.getByRole('dialog', { name: /^(駒を削除|準備をやり直す|新しい戦闘を始める)$/ })
  expect(dialog).toHaveTextContent(`${name}を削除しますか？`)
  fireEvent.click(within(dialog).getByRole('button', { name: '削除する' }))
}

describe('準備中/戦闘途中の追加・削除（#33）', () => {
  it('敵3体へ2体を追加し、既存の配置・移動力と選択を保持。追加取消は番号を消費しない', () => {
    render(<App />)
    prepare('0', '3')
    place('敵1', 1, 1)
    selectAndOpen(token('敵1'))
    click('敵1の移動力を減らす')
    click('駒を増やす')
    expect(within(form()).getByRole('textbox', { name: '味方の追加数' })).toHaveValue('0')
    expect(within(form()).getByRole('textbox', { name: '敵の追加数' })).toHaveValue('0')
    expect(within(form()).getByText('味方：あと10体追加できます')).toBeVisible()
    expect(within(form()).getByText('敵：あと7体追加できます')).toBeVisible()
    input('敵の追加数', '2')
    click('キャンセル')
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 敵1（敵・移動力4）')
    expect(pressed()).toEqual([cell(1, 1)])
    click('駒を増やす')
    expect(screen.getByRole('textbox', { name: '敵の追加数' })).toHaveValue('0')
    click('敵の追加数を増やす')
    expect(screen.getByRole('textbox', { name: '敵の追加数' })).toHaveValue('1')
    click('敵の追加数を減らす')
    input('敵の追加数', ' 02 ')
    click('追加する')
    expect(pending().getAllByRole('button')).toHaveLength(4)
    expect(token('敵4')).toHaveAccessibleName('未配置 敵4（敵・移動力5）')
    expect(token('敵5')).toBeVisible()
    expect(pressed()).toEqual([cell(1, 1)])
    expect(value('敵1')).toHaveTextContent(/^4$/)
    place('敵4', 2, 2)
    selectAndOpen(token('敵4'))
    click('敵4の移動力を増やす')
    expect(cell(2, 2)).toHaveAccessibleName('マス (2, 2) 敵4（敵・移動力6）')
  })

  it.each(['', '-1', '1.5', '3', 'a', '３', '1e1', '+1'])('残枠2に対する不正な「%s」は追加も±も無効、案内は現在の上限', (invalid) => {
    render(<App />)
    prepare('0', '8')
    click('駒を増やす')
    expect(screen.getByRole('button', { name: '追加する' })).toBeDisabled()
    expect(within(form()).getByText('味方か敵を1体以上にしてください')).toBeVisible()
    expect(screen.getByRole('textbox', { name: '敵の追加数' })).toHaveAccessibleDescription('0〜2体の整数を入力してください。')
    expect(screen.getByRole('button', { name: '敵の追加数を減らす' })).toBeDisabled()
    input('味方の追加数', '1')
    expect(within(form()).queryByText('味方か敵を1体以上にしてください')).not.toBeInTheDocument()
    input('敵の追加数', invalid)
    expect(screen.getByRole('textbox', { name: '敵の追加数' })).toHaveAccessibleDescription('0〜2の整数で入力してください')
    expect(screen.getByRole('button', { name: '敵の追加数を増やす' })).toBeDisabled()
    expect(screen.getByRole('button', { name: '敵の追加数を減らす' })).toBeDisabled()
    expect(screen.getByRole('button', { name: '追加する' })).toBeDisabled()
    input('敵の追加数', '1')
    click('敵の追加数を増やす')
    expect(screen.getByRole('textbox', { name: '敵の追加数' })).toHaveValue('2')
    expect(screen.getByRole('button', { name: '敵の追加数を増やす' })).toBeDisabled()
    expect(screen.getByRole('button', { name: '追加する' })).toBeEnabled()
    click('追加する')
    expect(token('敵10')).toBeVisible()
    click('駒を増やす')
    expect(within(form()).getByText('敵：あと0体追加できます')).toBeVisible()
    expect(screen.getByRole('button', { name: '敵の追加数を増やす' })).toBeDisabled()
  })

  it('削除取消は未配置/配置済みの選択・範囲を保持、実行は対象1体だけと選択を消す。欠番を再利用しない', () => {
    render(<App />)
    prepare('1', '3')
    place('味方1', 5, 5)
    place('敵1', 1, 1)
    for (const name of ['敵2', '敵1']) {
      selectAndOpen(token(name))
      const selected = pressed()
      const before = range().map((el) => el.getAttribute('aria-label'))
      click('この駒を削除')
      expect(screen.getByRole('button', { name: 'キャンセル' })).toHaveFocus()
      click('キャンセル')
      expect(screen.queryByRole('dialog', { name: '駒を削除' })).not.toBeInTheDocument()
      expect(screen.getByRole('button', { name: 'この駒を削除' })).toHaveFocus()
      expect(pressed()).toEqual(selected)
      expect(range().map((el) => el.getAttribute('aria-label'))).toEqual(before)
      expect(token(name)).toBeVisible()
      click('この駒を削除')
      click('削除する')
      expect(screen.queryByRole('button', { name: new RegExp(`(?:^未配置 | )${name}（`) })).not.toBeInTheDocument()
      expect(pressed()).toEqual([])
      expect(range()).toEqual([])
    }
    expect(cell(5, 5)).toHaveAccessibleName('マス (5, 5) 味方1（味方・移動力5）')
    remove('敵3') // 最後に発行した番号も再利用しない
    add()
    expect(token('敵4')).toBeVisible()
    expect(screen.getByText('全駒と設定を消して最初からやり直すこともできます。')).toBeVisible()
  })

  it.each([['閉じた', false], ['開いた', true]] as const)('追加数のエリアを%s状態で削除を実行した後は、他の操作へフォーカスを移さない', (_state, adding) => {
    render(<App />)
    prepare()
    if (adding) click('駒を増やす')
    remove('敵1')
    expect(screen.queryByRole('dialog', { name: '駒を削除' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '駒を増やす' })).not.toHaveFocus()
    if (adding) expect(screen.getByRole('textbox', { name: '味方の追加数' })).not.toHaveFocus()
    else expect(screen.queryByRole('textbox', { name: '味方の追加数' })).not.toBeInTheDocument()
    expect(document.body).toHaveFocus()
  })

  it('全削除でも準備の段階を保ち確定不可。やり直し取消は番号保持、実行は番号1/初期5へ戻る', () => {
    render(<App />)
    prepare()
    remove('敵1')
    expect(screen.getByRole('region', { name: '配置の準備' })).toBeVisible()
    expect(screen.getByRole('button', { name: '確定' })).toBeDisabled()
    expect(screen.getAllByRole('button', { name: /^マス / })).toHaveLength(100)
    click('準備をやり直す')
    click('キャンセル')
    add()
    expect(token('敵2')).toBeVisible()
    click('準備をやり直す')
    click('やり直す')
    prepare()
    expect(token('敵1')).toHaveAccessibleName('未配置 敵1（敵・移動力5）')
  })

  it('戦闘中の追加分は配置後も±0〜9で設定でき、再追加とまとめて明示確定。既存の駒は編集不可', () => {
    render(<App />)
    prepare('1', '0')
    selectAndOpen(token('味方1'))
    click('味方1の移動力を減らす')
    selectAndOpen(cell(1, 1))
    click('確定')
    selectAndOpen(token('味方1'))
    add()
    expect(pressed()).toEqual([cell(1, 1)])
    expect(settings()).toEqual([])
    expect(screen.getByRole('button', { name: '追加分を確定' })).toBeDisabled()
    selectAndOpen(token('敵1'))
    expect(value('敵1')).toHaveTextContent(/^5$/)
    for (let i = 0; i < 5; i += 1) click('敵1の移動力を減らす')
    expect(value('敵1')).toHaveTextContent(/^0$/)
    expect(screen.getByRole('button', { name: '敵1の移動力を減らす' })).toBeDisabled()
    selectAndOpen(cell(2, 1))
    selectAndOpen(token('敵1'))
    expect(value('敵1')).toHaveTextContent(/^0$/)
    expect(range()).toEqual([])
    for (let i = 0; i < 9; i += 1) click('敵1の移動力を増やす')
    expect(value('敵1')).toHaveTextContent(/^9$/)
    expect(screen.getByRole('button', { name: '敵1の移動力を増やす' })).toBeDisabled()
    expect(cell(10, 1)).toHaveAccessibleName('マス (10, 1) 移動範囲')
    expect(screen.getByRole('button', { name: '追加分を確定' })).toBeEnabled()
    add()
    expect(pressed()).toEqual([cell(2, 1)])
    expect(value('敵1')).toHaveTextContent(/^9$/)
    expect(screen.getByRole('button', { name: '追加分を確定' })).toBeDisabled()
    place('敵2', 3, 1)
    selectAndOpen(token('味方1'))
    expect(settings()).toEqual([])
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力4）')
    selectAndOpen(token('敵1'))
    click('追加分を確定')
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
    expect(screen.queryByRole('button', { name: '追加分を確定' })).not.toBeInTheDocument()
    expect(screen.queryByRole('group', { name: '未配置の駒' })).not.toBeInTheDocument()
    for (const name of ['敵1', '敵2']) {
      selectAndOpen(token(name))
      expect(settings()).toEqual([])
    }
    expect(cell(2, 1)).toHaveAccessibleName('マス (2, 1) 敵1（敵・移動力9）')
    selectAndOpen(cell(10, 10)) // 敵2の範囲外へ移動してもよい
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 敵2（敵・移動力5）')
  })

  it('未確定追加分をすべて削除すると追加準備終了。既存・戦闘と番号を保ち、新戦闘だけで番号を戻す', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    click('確定')
    add('0', '2')
    place('敵1', 2, 1)
    remove('敵1')
    expect(screen.getByRole('button', { name: '追加分を確定' })).toBeDisabled()
    remove('敵2')
    expect(screen.queryByRole('button', { name: '追加分を確定' })).not.toBeInTheDocument()
    expect(screen.queryByRole('group', { name: '未配置の駒' })).not.toBeInTheDocument()
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5）')
    remove('味方1')
    expect(screen.getByRole('region', { name: '戦闘中' })).toBeVisible()
    click('新しい戦闘を始める')
    click('キャンセル')
    add()
    expect(token('敵3')).toBeVisible()
    click('新しい戦闘を始める')
    click('始める')
    prepare()
    expect(token('敵1')).toHaveAccessibleName('未配置 敵1（敵・移動力5）')
  })

  it('追加分を確定すると空きマスの選択も解除する', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    click('確定')
    add()
    place('敵1', 2, 1)
    selectAndOpen(cell(10, 10))
    expect(pressed()).toEqual([cell(10, 10)])
    click('追加分を確定')
    expect(pressed()).toEqual([])
  })

  it('追加数の入力中のやり直しは取消で入力保持、実行でフォームを閉じ番号1へ戻る', () => {
    render(<App />)
    prepare()
    click('駒を増やす')
    input('敵の追加数', '2')
    click('準備をやり直す')
    fireEvent.click(within(screen.getByRole('dialog', { name: /^(駒を削除|準備をやり直す|新しい戦闘を始める)$/ })).getByRole('button', { name: 'キャンセル' }))
    expect(screen.getByRole('textbox', { name: '敵の追加数' })).toHaveValue('2')
    click('準備をやり直す')
    click('やり直す')
    prepare()
    expect(screen.queryByRole('group', { name: '駒の追加数' })).not.toBeInTheDocument()
    expect(token('敵1')).toHaveAccessibleName('未配置 敵1（敵・移動力5）')
  })

  it('99番を省略せず配置でき、削除後も敵の番号は枯渇、味方だけ追加できる', () => {
    render(<App />)
    prepare('0', '10')
    for (let batch = 0; batch < 9; batch += 1) {
      for (let n = batch * 10 + 1; n <= batch * 10 + 10; n += 1) remove(`敵${n}`)
      if (batch < 8) add('0', '10')
    }
    add('0', '8') // 敵91〜98: 8体、発行98
    click('駒を増やす')
    expect(within(form()).getByText('敵：あと1体追加できます')).toBeVisible()
    input('敵の追加数', '2')
    expect(screen.getByRole('button', { name: '追加する' })).toBeDisabled()
    input('敵の追加数', '1')
    click('追加する')
    expect(within(token('敵99')).getByText('99')).toBeVisible()
    place('敵99', 10, 10)
    expect(within(cell(10, 10)).getByText('99')).toBeVisible()
    remove('敵99')
    click('駒を増やす')
    expect(within(form()).getByText('敵：あと0体追加できます')).toBeVisible()
    expect(screen.getByRole('button', { name: '敵の追加数を増やす' })).toBeDisabled()
    input('敵の追加数', '1')
    expect(screen.getByRole('button', { name: '追加する' })).toBeDisabled()
    input('敵の追加数', '0')
    input('味方の追加数', '1')
    click('追加する')
    expect(token('味方1')).toBeVisible()
  }, 20000)
})
