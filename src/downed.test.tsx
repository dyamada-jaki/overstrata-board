import { fireEvent, render, screen, within } from '@testing-library/react'
import App from './App.tsx'

const click = (name: string | RegExp) => fireEvent.click(screen.getByRole('button', { name }))
const cell = (x: number, y: number) => screen.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const token = (name: string) => {
  const group = screen.queryByRole('group', { name: '未配置の駒' })
  return (group && within(group).queryByRole('button', { name: new RegExp(`^未配置 ${name}（`) }))
    || screen.getByRole('button', { name: new RegExp(`(?:^未配置 | )${name}（`) })
}
const input = (name: string, value: string) => fireEvent.change(screen.getByRole('textbox', { name }), { target: { value } })
const pressed = () => screen.queryAllByRole('button', { pressed: true })
const range = () => screen.queryAllByRole('button', { name: / 移動範囲$/ }).map((button) => button.getAttribute('aria-label'))
const circle = (element: HTMLElement) => element.querySelector('.board-token')!
const toggle = () => screen.getByRole('button', { name: /^(倒れた状態にする|通常に戻す)$/ })
function prepare(ally: string, enemy: string) {
  input('味方の数', ally)
  input('敵の数', enemy)
  click('駒を用意する')
}
function place(name: string, x: number, y: number) {
  fireEvent.click(token(name))
  fireEvent.click(cell(x, y))
}

describe('倒れた状態の切り替えと表示（spec.md 2.2 / #34）', () => {
  it('準備中に未配置の駒を選び、確認なしで切り替える。対象だけが変わり、選択とフォーカスはボタンに残る', () => {
    render(<App />)
    prepare('2', '0')
    fireEvent.click(token('味方1'))
    const panel = screen.getByText('状態：通常').closest('.selected-piece') as HTMLElement
    expect(within(panel).getByText('味方1の移動力')).toBeVisible()
    const button = toggle()
    expect(button).toHaveTextContent('倒れた状態にする')
    button.focus()
    fireEvent.click(button)
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(toggle()).toBe(button)
    expect(button).toHaveTextContent('通常に戻す')
    expect(button).toHaveFocus()
    expect(within(panel).getByText('状態：倒れている')).toBeVisible()
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力5・倒れた状態）')
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'true')
    expect(circle(token('味方1'))).toHaveClass('board-token-downed')
    expect(panel.querySelector('.board-token')).toHaveClass('board-token-downed')
    expect(token('味方2')).toHaveAccessibleName('未配置 味方2（味方・移動力5）')
    expect(circle(token('味方2'))).not.toHaveClass('board-token-downed')

    fireEvent.click(button)
    expect(button).toHaveTextContent('倒れた状態にする')
    expect(within(panel).getByText('状態：通常')).toBeVisible()
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力5）')
    expect(circle(token('味方1'))).not.toHaveClass('board-token-downed')
  })

  it('未配置の駒は通常・倒れた状態とも目安を出さず、倒れたまま初回配置しても再選択で目安を出さず動かない。通常に戻すと目安が出て動ける（#50）', () => {
    render(<App />)
    prepare('1', '0')
    fireEvent.click(token('味方1'))
    expect(range()).toEqual([])
    click('倒れた状態にする')
    expect(range()).toEqual([])
    fireEvent.click(cell(3, 3))
    expect(cell(3, 3)).toHaveAccessibleName('マス (3, 3) 味方1（味方・移動力5・倒れた状態）')
    expect(circle(cell(3, 3))).toHaveClass('board-token-downed')
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])

    fireEvent.click(cell(3, 3))
    expect(pressed()).toEqual([cell(3, 3)])
    expect(screen.getByText('状態：倒れている')).toBeVisible()
    expect(range()).toEqual([])
    fireEvent.click(cell(4, 3))
    fireEvent.click(cell(10, 10))
    expect(cell(3, 3)).toHaveAccessibleName('マス (3, 3) 味方1（味方・移動力5・倒れた状態）')
    expect(cell(4, 3)).toHaveAccessibleName('マス (4, 3)')
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10)')
    expect(pressed()).toEqual([cell(3, 3)])
    expect(range()).toEqual([])

    click('通常に戻す')
    expect(pressed()).toEqual([cell(3, 3)])
    expect(range()).toContain('マス (4, 3) 移動範囲')
    expect(range()).toContain('マス (8, 3) 移動範囲')
    expect(range()).not.toContain('マス (9, 3) 移動範囲')
    fireEvent.click(cell(10, 10))
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 味方1（味方・移動力5）')
  })

  it('確定後の配置済みの駒を倒すと、位置・番号・移動力・選択を保って目安がすぐ消えて動けなくなり、通常に戻すと同じ目安が出て範囲内外へ動ける（#50）', () => {
    render(<App />)
    prepare('2', '0')
    place('味方1', 1, 1)
    place('味方2', 5, 1)
    click('確定')
    fireEvent.click(cell(1, 1))
    const before = range()
    expect(before).toContain('マス (2, 2) 移動範囲')
    const button = toggle()
    button.focus()
    click('倒れた状態にする')
    expect(button).toHaveFocus()
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5・倒れた状態）')
    expect(circle(cell(1, 1))).toHaveTextContent('1')
    expect(pressed()).toEqual([cell(1, 1)])
    expect(screen.getByText('状態：倒れている')).toBeVisible()
    expect(range()).toEqual([])
    expect(cell(5, 1)).toHaveAccessibleName('マス (5, 1) 味方2（味方・移動力5）')

    fireEvent.click(cell(2, 2))
    fireEvent.click(cell(10, 10))
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5・倒れた状態）')
    expect(pressed()).toEqual([cell(1, 1)])
    expect(range()).toEqual([])

    fireEvent.click(cell(1, 1))
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])

    fireEvent.click(cell(1, 1))
    // 解除で操作パネルが消えたため、再選択後のボタンは別の要素になる。
    const again = toggle()
    again.focus()
    click('通常に戻す')
    expect(again).toHaveFocus()
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5）')
    expect(circle(cell(1, 1))).not.toHaveClass('board-token-downed')
    expect(pressed()).toEqual([cell(1, 1)])
    expect(range()).toEqual(before)
    fireEvent.click(cell(2, 2))
    expect(cell(2, 2)).toHaveAccessibleName('マス (2, 2) 味方1（味方・移動力5）')
    expect(pressed()).toEqual([])
    fireEvent.click(cell(2, 2))
    fireEvent.click(cell(10, 10))
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 味方1（味方・移動力5）')
  })

  it('通常の駒と倒れた駒を選び替えると選んだ駒の状態で目安が切り替わり、同じ駒の再タップで解除すると目安も消える（#50）', () => {
    render(<App />)
    prepare('2', '0')
    place('味方1', 1, 1)
    place('味方2', 5, 1)
    click('確定')
    fireEvent.click(cell(5, 1))
    const second = range()
    expect(second).toContain('マス (6, 1) 移動範囲')
    fireEvent.click(cell(5, 1))
    fireEvent.click(cell(1, 1))
    click('倒れた状態にする')
    expect(range()).toEqual([])

    fireEvent.click(cell(5, 1))
    expect(pressed()).toEqual([cell(5, 1)])
    expect(screen.getByText('状態：通常')).toBeVisible()
    expect(range()).toEqual(second)

    fireEvent.click(cell(1, 1))
    expect(pressed()).toEqual([cell(1, 1)])
    expect(screen.getByText('状態：倒れている')).toBeVisible()
    expect(range()).toEqual([])

    fireEvent.click(cell(5, 1))
    fireEvent.click(cell(5, 1))
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
    expect(screen.queryByText(/^状態：/)).not.toBeInTheDocument()
  })

  it('準備中は保持している移動力で、追加分は確定前でも、倒すと目安が消え、通常に戻すと同じ目安が出る（#50）', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    fireEvent.click(cell(1, 1))
    click('味方1の移動力を減らす')
    click('味方1の移動力を減らす')
    click('味方1の移動力を減らす')
    const two = range()
    expect(two).toContain('マス (3, 1) 移動範囲')
    expect(two).not.toContain('マス (4, 1) 移動範囲')
    click('倒れた状態にする')
    expect(range()).toEqual([])
    expect(screen.getByRole('group', { name: '味方1の移動力' })).toHaveTextContent('2')
    click('通常に戻す')
    expect(range()).toEqual(two)
    fireEvent.click(cell(1, 1))
    click('確定')

    click('駒を増やす')
    input('敵の追加数', '1')
    click('追加する')
    place('敵1', 5, 5)
    fireEvent.click(cell(5, 5))
    const added = range()
    expect(added).toContain('マス (6, 5) 移動範囲')
    click('倒れた状態にする')
    expect(range()).toEqual([])
    fireEvent.click(cell(6, 5))
    fireEvent.click(cell(10, 10))
    expect(cell(5, 5)).toHaveAccessibleName('マス (5, 5) 敵1（敵・移動力5・倒れた状態）')
    expect(pressed()).toEqual([cell(5, 5)])
    click('通常に戻す')
    expect(range()).toEqual(added)
    fireEvent.click(cell(10, 10))
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 敵1（敵・移動力5）')
  })

  it('倒れた駒も1マスを占有し、他の駒を選んでそのマスを押すと選択だけが切り替わる', () => {
    render(<App />)
    prepare('1', '1')
    place('味方1', 1, 1)
    fireEvent.click(cell(1, 1))
    click('倒れた状態にする')
    fireEvent.click(token('敵1'))
    fireEvent.click(cell(1, 1))
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5・倒れた状態）')
    expect(token('敵1')).toHaveAttribute('aria-pressed', 'false')
    expect(pressed()).toEqual([cell(1, 1)])
  })

  it('確定・途中の追加・削除・追加分の確定で状態を引き継ぎ、追加した駒と新しい戦闘の駒は通常で始まる', () => {
    render(<App />)
    prepare('1', '0')
    fireEvent.click(token('味方1'))
    click('倒れた状態にする')
    fireEvent.click(cell(1, 1))
    click('確定')
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5・倒れた状態）')

    click('駒を増やす')
    input('敵の追加数', '2')
    click('追加する')
    expect(token('敵1')).toHaveAccessibleName('未配置 敵1（敵・移動力5）')
    fireEvent.click(token('敵2'))
    fireEvent.click(screen.getByText('この駒を削除', { selector: 'button' }))
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '削除する' }))
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5・倒れた状態）')

    fireEvent.click(token('敵1'))
    click('倒れた状態にする')
    fireEvent.click(cell(2, 1))
    click('追加分を確定')
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5・倒れた状態）')
    expect(cell(2, 1)).toHaveAccessibleName('マス (2, 1) 敵1（敵・移動力5・倒れた状態）')

    click('新しい戦闘を始める')
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '始める' }))
    prepare('1', '1')
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力5）')
    expect(token('敵1')).toHaveAccessibleName('未配置 敵1（敵・移動力5）')
  })
})
