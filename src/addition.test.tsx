import { fireEvent, render, screen, within } from '@testing-library/react'
import App from './App.tsx'

const click = (name: string | RegExp) => fireEvent.click(screen.getByRole('button', { name }))
const cell = (x: number, y: number) => screen.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const token = (name: string) => screen.getByRole('button', { name: new RegExp(`(?:^未配置 | )${name}（`) })
const pressed = () => screen.queryAllByRole('button', { pressed: true })
const range = () => screen.queryAllByRole('button', { name: / 移動範囲$/ }).map((el) => el.getAttribute('aria-label'))
const occupants = () => screen.queryAllByRole('button', { name: /^マス .*（/ }).map((el) => el.getAttribute('aria-label'))
const unplacedNames = () => screen.queryAllByRole('button', { name: /^未配置 / }).map((el) => el.getAttribute('aria-label'))
const area = () => screen.getByRole('group', { name: '追加する駒の数' })
const queryArea = () => screen.queryByRole('group', { name: '追加する駒の数' })
const addField = (side: '味方' | '敵') => within(area()).getByRole('textbox', { name: `${side}の追加数` })
const addButton = (side: '味方' | '敵', delta: '減らす' | '増やす') => within(area()).getByRole('button', { name: `${side}の追加数を${delta}` })
const setting = (name: string) => screen.getByRole('group', { name: `${name}の移動力` })
const settings = () => screen.queryAllByRole('group', { name: /の移動力$/ })
const value = (name: string) => within(setting(name)).getByRole('status')
const times = (button: () => HTMLElement, count: number) => {
  for (let i = 0; i < count; i += 1) fireEvent.click(button())
}
function prepare(ally: string, enemy: string) {
  fireEvent.change(screen.getByRole('textbox', { name: '味方の数' }), { target: { value: ally } })
  fireEvent.change(screen.getByRole('textbox', { name: '敵の数' }), { target: { value: enemy } })
  click('駒を用意する')
}
function place(name: string, x: number, y: number) {
  fireEvent.click(token(name))
  fireEvent.click(cell(x, y))
}
function input(side: '味方' | '敵', count: string) {
  fireEvent.change(addField(side), { target: { value: count } })
}
function add(ally: string, enemy: string) {
  click('駒を増やす')
  input('味方', ally)
  input('敵', enemy)
  click('追加する')
}
function remove(name: string) {
  fireEvent.click(token(name))
  click('この駒を削除')
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '削除する' }))
}
/** 敵3体を配置して確定した戦闘中の盤面。 */
function activeWithThreeEnemies() {
  prepare('0', '3')
  place('敵1', 1, 1)
  place('敵2', 2, 1)
  place('敵3', 3, 1)
  click('確定')
}

describe('追加数のエリア（#33）', () => {
  it.each(['準備中', '戦闘中'])('%sに「駒を増やす」で味方・敵の追加数のエリアが開き、初期値は双方0', (phase) => {
    render(<App />)
    if (phase === '準備中') prepare('0', '3')
    else activeWithThreeEnemies()
    expect(queryArea()).not.toBeInTheDocument()
    click('駒を増やす')
    expect(area()).toBeVisible()
    expect(addField('味方')).toHaveValue('0')
    expect(addField('敵')).toHaveValue('0')
    expect(addField('味方')).toHaveAttribute('inputmode', 'numeric')
    expect(within(area()).getByText('味方か敵を1体以上にしてください')).toBeVisible()
    expect(within(area()).getByRole('button', { name: '追加する' })).toBeDisabled()
    expect(screen.queryByRole('button', { name: '駒を増やす' })).not.toBeInTheDocument()
  })

  it('敵3体に敵の追加数2を指定すると敵5体になり、既存の配置と移動力は変わらない', () => {
    render(<App />)
    activeWithThreeEnemies()
    const before = occupants()
    click('駒を増やす')
    fireEvent.click(addButton('敵', '増やす'))
    fireEvent.click(addButton('敵', '増やす'))
    expect(addField('敵')).toHaveValue('2')
    click('追加する')
    expect(queryArea()).not.toBeInTheDocument()
    expect(occupants()).toEqual(before)
    expect(unplacedNames()).toEqual(['未配置 敵4（敵・移動力5）', '未配置 敵5（敵・移動力5）'])
    expect(screen.getByRole('heading', { name: '未配置：2体' })).toBeVisible()
    expect(screen.getByRole('region', { name: '戦闘中' })).toBeVisible()
  })

  it('「キャンセル」で入力を取り消して閉じ、駒・番号は増えず、再度開くと0から', () => {
    render(<App />)
    activeWithThreeEnemies()
    fireEvent.click(cell(1, 1))
    const before = { occupied: occupants(), selected: pressed(), range: range() }
    click('駒を増やす')
    input('敵', '2')
    click('キャンセル')
    expect(queryArea()).not.toBeInTheDocument()
    expect(occupants()).toEqual(before.occupied)
    expect(pressed()).toEqual(before.selected)
    expect(range()).toEqual(before.range)
    expect(unplacedNames()).toEqual([])
    click('駒を増やす')
    expect(addField('敵')).toHaveValue('0')
    input('敵', '1')
    click('追加する')
    expect(unplacedNames()).toEqual(['未配置 敵4（敵・移動力5）'])
  })

  it('各陣営に「あとN体追加できます」を表示し、10体の陣営は0体', () => {
    render(<App />)
    prepare('10', '3')
    click('駒を増やす')
    expect(addField('味方')).toHaveAccessibleDescription('あと0体追加できます')
    expect(addField('敵')).toHaveAccessibleDescription('あと7体追加できます')
    expect(within(area()).getByText('あと0体追加できます')).toBeVisible()
    expect(within(area()).getByText('あと7体追加できます')).toBeVisible()
    expect(addButton('味方', '減らす')).toBeDisabled()
    expect(addButton('味方', '増やす')).toBeDisabled()
    input('味方', '1')
    expect(addField('味方')).toHaveAttribute('aria-invalid', 'true')
    expect(within(area()).getByText('0〜0の整数で入力してください')).toBeVisible()
    expect(within(area()).getByRole('button', { name: '追加する' })).toBeDisabled()
    input('味方', '0')
    input('敵', '1')
    click('追加する')
    expect(unplacedNames().filter((name) => name!.includes('敵'))).toHaveLength(4)
  })

  it('−/＋は0〜追加可能数で止まり、上限超過・不正な入力・双方0では「追加する」を押せない', () => {
    render(<App />)
    prepare('0', '3')
    click('駒を増やす')
    const approve = () => within(area()).getByRole('button', { name: '追加する' })
    expect(addButton('敵', '減らす')).toBeDisabled()
    times(() => addButton('敵', '増やす'), 7)
    expect(addField('敵')).toHaveValue('7')
    expect(addButton('敵', '増やす')).toBeDisabled()
    expect(approve()).toBeEnabled()
    for (const invalid of ['8', '-1', '1.5', '３', '']) {
      input('敵', invalid)
      expect(addField('敵')).toHaveAttribute('aria-invalid', 'true')
      expect(addField('敵')).toHaveAccessibleDescription('0〜7の整数で入力してください')
      expect(approve()).toBeDisabled()
      expect(addButton('敵', '増やす')).toBeDisabled()
      expect(addButton('敵', '減らす')).toBeDisabled()
    }
    input('敵', '0')
    expect(approve()).toBeDisabled()
    input('味方', '10')
    expect(approve()).toBeEnabled()
    input('敵', '8')
    expect(approve()).toBeDisabled()
    input('敵', ' 07 ')
    expect(approve()).toBeEnabled()
    expect(addField('敵')).toHaveAccessibleDescription('あと7体追加できます')
  })

  it('追加した駒は一覧から選んで空きマスへ置け、置いた後は選択と範囲を解除する', () => {
    render(<App />)
    activeWithThreeEnemies()
    add('1', '0')
    expect(unplacedNames()).toEqual(['未配置 味方1（味方・移動力5）'])
    fireEvent.click(token('味方1'))
    expect(pressed()).toHaveLength(1)
    fireEvent.click(cell(1, 1)) // 既に駒がいるマスは選択の切り替えで、追加した駒は置かれない
    expect(pressed()).toEqual([cell(1, 1)])
    expect(unplacedNames()).toEqual(['未配置 味方1（味方・移動力5）'])
    place('味方1', 5, 5)
    expect(cell(5, 5)).toHaveAccessibleName('マス (5, 5) 味方1（味方・移動力5）')
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
    expect(screen.queryByRole('group', { name: '未配置の駒' })).not.toBeInTheDocument()
    fireEvent.click(cell(5, 5))
    fireEvent.click(cell(10, 10))
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 味方1（味方・移動力5）')
  })

  it('「追加する」の後も選択中の駒の選択を保つ', () => {
    render(<App />)
    activeWithThreeEnemies()
    fireEvent.click(cell(2, 1))
    const selected = pressed()
    add('0', '1')
    expect(pressed()).toEqual(selected)
  })
})

describe('追加する駒の移動力と確定（#33）', () => {
  it('準備中に追加した駒は初期値5で、他の駒と同じく「確定」まで変更でき、確定後は欄が出ない', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    add('0', '1')
    fireEvent.click(token('敵1'))
    expect(value('敵1')).toHaveTextContent(/^5$/)
    times(() => within(setting('敵1')).getByRole('button', { name: '敵1の移動力を増やす' }), 4)
    expect(value('敵1')).toHaveTextContent(/^9$/)
    expect(within(setting('敵1')).getByRole('button', { name: '敵1の移動力を増やす' })).toBeDisabled()
    fireEvent.click(cell(4, 4))
    fireEvent.click(cell(1, 1))
    fireEvent.click(within(setting('味方1')).getByRole('button', { name: '味方1の移動力を減らす' }))
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力4）')
    click('確定')
    fireEvent.click(cell(4, 4))
    expect(settings()).toEqual([])
    expect(cell(4, 4)).toHaveAccessibleName('マス (4, 4) 敵1（敵・移動力9）')
  })

  it('戦闘中の追加分は未配置・配置済みとも変更でき、すべて置くまで「追加分を確定」は押せず、置いただけでは確定しない', () => {
    render(<App />)
    activeWithThreeEnemies()
    expect(screen.queryByRole('button', { name: '追加分を確定' })).not.toBeInTheDocument()
    add('0', '2')
    const confirm = () => screen.getByRole('button', { name: '追加分を確定' })
    expect(confirm()).toBeDisabled()
    fireEvent.click(token('敵4'))
    fireEvent.click(within(setting('敵4')).getByRole('button', { name: '敵4の移動力を減らす' }))
    expect(token('敵4')).toHaveAccessibleName('未配置 敵4（敵・移動力4）')
    fireEvent.click(cell(5, 5))
    expect(confirm()).toBeDisabled()
    place('敵5', 9, 9)
    expect(confirm()).toBeEnabled()
    fireEvent.click(cell(5, 5))
    expect(settings()).toHaveLength(1)
    expect(range()).toContain('マス (5, 1) 移動範囲')
    expect(range()).not.toContain('マス (5, 10) 移動範囲')
    times(() => within(setting('敵4')).getByRole('button', { name: '敵4の移動力を増やす' }), 2)
    // 移動力6: (5,5)→(5,10) は距離5で範囲に入る。他の駒・確定済みの駒は変わらない。
    expect(range()).toContain('マス (5, 10) 移動範囲')
    expect(cell(5, 5)).toHaveAccessibleName(/^マス \(5, 5\) 敵4（敵・移動力6）/)
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 敵1（敵・移動力5）')
    expect(cell(9, 9)).toHaveAccessibleName('マス (9, 9) 敵5（敵・移動力5）')
  })

  it('「追加分を確定」で値を引き継ぎ、選択と範囲を解除し、追加分の移動力欄も出なくなる', () => {
    render(<App />)
    activeWithThreeEnemies()
    add('0', '1')
    place('敵4', 5, 5)
    fireEvent.click(cell(5, 5))
    fireEvent.click(within(setting('敵4')).getByRole('button', { name: '敵4の移動力を増やす' }))
    expect(pressed()).toHaveLength(1)
    expect(range().length).toBeGreaterThan(0)
    click('追加分を確定')
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
    expect(screen.queryByRole('button', { name: '追加分を確定' })).not.toBeInTheDocument()
    expect(cell(5, 5)).toHaveAccessibleName('マス (5, 5) 敵4（敵・移動力6）')
    fireEvent.click(cell(5, 5))
    expect(settings()).toEqual([])
    expect(screen.getByRole('button', { name: 'この駒を削除' })).toBeVisible()
    fireEvent.click(cell(10, 10))
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 敵4（敵・移動力6）')
  })

  it('戦闘中、確定済みの駒は移動力を変更できない', () => {
    render(<App />)
    activeWithThreeEnemies()
    fireEvent.click(cell(1, 1))
    expect(settings()).toEqual([])
    expect(screen.getByRole('button', { name: 'この駒を削除' })).toBeVisible()
    add('0', '1')
    fireEvent.click(cell(1, 1))
    expect(settings()).toEqual([])
  })

  it('「追加分を確定」の前でもさらに追加でき、先の追加分の配置と移動力を保ってまとめて確定する', () => {
    render(<App />)
    activeWithThreeEnemies()
    add('0', '1')
    place('敵4', 5, 5)
    fireEvent.click(cell(5, 5))
    times(() => within(setting('敵4')).getByRole('button', { name: '敵4の移動力を増やす' }), 2)
    add('1', '1')
    expect(cell(5, 5)).toHaveAccessibleName(/^マス \(5, 5\) 敵4（敵・移動力7）/)
    expect(unplacedNames()).toEqual(['未配置 味方1（味方・移動力5）', '未配置 敵5（敵・移動力5）'])
    expect(screen.getByRole('button', { name: '追加分を確定' })).toBeDisabled()
    place('味方1', 6, 6)
    place('敵5', 7, 7)
    click('追加分を確定')
    for (const [x, y] of [[5, 5], [6, 6], [7, 7]] as const) {
      fireEvent.click(cell(x, y))
      expect(settings()).toEqual([])
      fireEvent.click(cell(x, y))
    }
    expect(cell(5, 5)).toHaveAccessibleName('マス (5, 5) 敵4（敵・移動力7）')
  })

  it('戦闘中の追加分をすべて削除すると「追加分を確定」なしで追加の準備を終え、既存の駒と戦闘中の状態を保つ', () => {
    render(<App />)
    activeWithThreeEnemies()
    const before = occupants()
    add('0', '2')
    place('敵4', 5, 5)
    remove('敵4')
    expect(screen.getByRole('button', { name: '追加分を確定' })).toBeDisabled()
    remove('敵5')
    expect(screen.queryByRole('button', { name: '追加分を確定' })).not.toBeInTheDocument()
    expect(screen.queryByRole('group', { name: '未配置の駒' })).not.toBeInTheDocument()
    expect(occupants()).toEqual(before)
    expect(screen.getByRole('region', { name: '戦闘中' })).toBeVisible()
    expect(screen.getByRole('heading', { name: '準備完了' })).toBeVisible()
    add('0', '1')
    expect(unplacedNames()).toEqual(['未配置 敵6（敵・移動力5）'])
  })
})

describe('番号の発行と上限（#33）', () => {
  it('敵1・2・3から敵2を削除して追加すると敵4、最後の敵4を削除しても次は敵5。既存の番号は変えない', () => {
    render(<App />)
    activeWithThreeEnemies()
    remove('敵2')
    add('0', '1')
    expect(unplacedNames()).toEqual(['未配置 敵4（敵・移動力5）'])
    remove('敵4')
    add('0', '1')
    expect(unplacedNames()).toEqual(['未配置 敵5（敵・移動力5）'])
    expect(occupants()).toEqual(['マス (1, 1) 敵1（敵・移動力5）', 'マス (3, 1) 敵3（敵・移動力5）'])
  })

  it('最後に発行した敵3を削除しても、次は敵4', () => {
    render(<App />)
    prepare('0', '3')
    remove('敵3')
    add('0', '1')
    expect(unplacedNames()).toEqual(['未配置 敵1（敵・移動力5）', '未配置 敵2（敵・移動力5）', '未配置 敵4（敵・移動力5）'])
  })

  it('現在8体・発行済み98なら追加は1体（99番）だけで、99番の後は9体でも追加できず、もう一方の陣営は追加できる', () => {
    render(<App />)
    prepare('0', '10')
    // 全削除と10体の追加を繰り返し、敵の番号を98まで発行する（現在8体: 敵91〜98）。
    let first = 1
    for (let round = 0; round < 9; round += 1) {
      for (let number = first; number < first + 10; number += 1) remove(`敵${number}`)
      first += 10
      add('0', round < 8 ? '10' : '8')
    }
    expect(unplacedNames()).toHaveLength(8)
    expect(unplacedNames()[0]).toBe('未配置 敵91（敵・移動力5）')
    click('駒を増やす')
    expect(addField('敵')).toHaveAccessibleDescription('あと1体追加できます')
    expect(addField('味方')).toHaveAccessibleDescription('あと10体追加できます')
    input('敵', '2')
    expect(addField('敵')).toHaveAccessibleDescription('0〜1の整数で入力してください')
    expect(within(area()).getByRole('button', { name: '追加する' })).toBeDisabled()
    input('敵', '1')
    click('追加する')
    expect(unplacedNames().at(-1)).toBe('未配置 敵99（敵・移動力5）')
    expect(within(token('敵99')).getByText('99')).toBeVisible()
    place('敵99', 10, 10)
    expect(within(cell(10, 10)).getByText('99')).toBeVisible()
    click('駒を増やす')
    expect(addField('敵')).toHaveAccessibleDescription('あと0体追加できます')
    expect(addButton('敵', '増やす')).toBeDisabled()
    click('キャンセル')
    remove('敵99')
    click('駒を増やす')
    expect(addField('敵')).toHaveAccessibleDescription('あと0体追加できます')
    input('味方', '1')
    click('追加する')
    // 一覧は味方の行が先（spec.md 2.2）。
    expect(unplacedNames()[0]).toBe('未配置 味方1（味方・移動力5）')
  }, 60_000)

  it.each([
    ['準備をやり直す', 'やり直す'],
    ['新しい戦闘を始める', '始める'],
  ])('「%s」で全体をクリアすると番号も1から、取り消すと発行状況を保つ', (reset, approve) => {
    render(<App />)
    if (reset === '新しい戦闘を始める') activeWithThreeEnemies()
    else prepare('0', '3')
    remove('敵3')
    click(reset)
    click('キャンセル')
    add('0', '1')
    expect(unplacedNames().at(-1)).toBe('未配置 敵4（敵・移動力5）')
    click(reset)
    click(approve)
    prepare('0', '2')
    expect(unplacedNames()).toEqual(['未配置 敵1（敵・移動力5）', '未配置 敵2（敵・移動力5）'])
  })
})
