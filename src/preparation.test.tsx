import { setCount } from './test/counts.ts'
import { fireEvent, render, screen, within } from '@testing-library/react'
import App from './App.tsx'

const click = (name: string | RegExp) => fireEvent.click(screen.getByRole('button', { name }))
const field = (side: '味方' | '敵') => screen.getByRole('status', { name: `${side}の数` })
const input = (side: '味方' | '敵', value: string) => setCount(`${side}の数`, value)
const cell = (x: number, y: number) => screen.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const token = (name: string) => screen.getByRole('button', { name: new RegExp(`(?:^未配置 | )${name}（`) })
const pressed = () => screen.queryAllByRole('button', { pressed: true })
const range = () => screen.queryAllByRole('button', { name: / 移動範囲$/ })
const unplaced = () => screen.getByRole('group', { name: '未配置の駒' })
const occupants = () => screen.queryAllByRole('button', { name: /^マス .*（/ }).map((el) => el.getAttribute('aria-label'))
function prepare(ally = '2', enemy = '1') {
  input('味方', ally)
  input('敵', enemy)
  click('駒を用意する')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(screen.getByRole('region', { name: '配置の準備' })).toBeVisible()
  expect(screen.getByRole('heading', { name: '駒を配置' })).toBeVisible()
}
function place(name: string, x: number, y: number) {
  fireEvent.click(token(name))
  fireEvent.click(cell(x, y))
}
function expectInitial() {
  expect(field('味方')).toHaveTextContent(/^0$/)
  expect(field('敵')).toHaveTextContent(/^0$/)
  expect(occupants()).toEqual([])
  expect(pressed()).toEqual([])
  expect(range()).toEqual([])
  expect(screen.queryByRole('group', { name: '未配置の駒' })).not.toBeInTheDocument()
  expect(screen.getByRole('button', { name: '駒を用意する' })).toBeDisabled()
  expect(screen.queryByRole('button', { name: '確定' })).not.toBeInTheDocument()
}

describe('数の指定（承認された入力仕様）', () => {
  it('空の100マス・0/0・案内から始まり、初期段階ではやり直しも確定も出さない', () => {
    render(<App />)
    expectInitial()
    expect(screen.getAllByRole('button', { name: /^マス / })).toHaveLength(100)
    expect(screen.getByText('味方か敵を1体以上にしてください')).toBeVisible()
    expect(screen.queryByRole('button', { name: '準備をやり直す' })).not.toBeInTheDocument()
    expect(document.body).toHaveFocus()
    expect(field('味方')).toHaveAccessibleDescription('「−」「＋」で、それぞれ0〜10体を指定してください。')
    expect(field('敵')).toHaveAccessibleDescription('「−」「＋」で、それぞれ0〜10体を指定してください。')
  })

  it('−/＋は1ずつ増減し、0と10の端では範囲を超えない', () => {
    render(<App />)
    expect(screen.getByRole('button', { name: '味方の数を減らす' })).toBeDisabled()
    click('味方の数を増やす')
    expect(field('味方')).toHaveTextContent(/^1$/)
    expect(screen.getByText('味方か敵を1体以上にしてください')).not.toBeVisible() // #45: 表示領域を残して文だけ隠す
    expect(field('敵')).toHaveTextContent(/^0$/)
    click('味方の数を減らす')
    expect(field('味方')).toHaveTextContent(/^0$/)
    input('敵', '9')
    expect(screen.getByText('味方か敵を1体以上にしてください')).not.toBeVisible() // #45: 表示領域を残して文だけ隠す
    click('敵の数を増やす')
    expect(field('敵')).toHaveTextContent(/^10$/)
    expect(screen.getByRole('button', { name: '敵の数を増やす' })).toBeDisabled()
    click('敵の数を減らす')
    expect(field('敵')).toHaveTextContent(/^9$/)
  })

  it('数値は表示専用で、空欄や不正値の入力・入力エラー行を設けない', () => {
    render(<App />)
    expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
    expect(screen.queryByRole('spinbutton')).not.toBeInTheDocument()
    expect(document.querySelector('[contenteditable="true"], [aria-invalid], .input-error')).toBeNull()
    expect(document.body).toHaveFocus()
    for (const side of ['味方', '敵'] as const) {
      expect(field(side).tagName).toBe('OUTPUT')
      expect(field(side)).not.toHaveAttribute('tabindex')
      fireEvent.click(field(side))
      expect(field(side)).not.toHaveFocus()
    }
    click('敵の数を増やす')
    expect(field('敵')).toHaveTextContent(/^1$/)
    expect(screen.getByRole('button', { name: '駒を用意する' })).toBeEnabled()
  })

  it.each([['0', '1', '敵1'], ['1', '0', '味方1']])('片側だけ（味方%s/敵%s）でも用意する', (ally, enemy, name) => {
    render(<App />)
    prepare(ally, enemy)
    expect(within(unplaced()).getAllByRole('button')).toEqual([token(name)])
    expect(occupants()).toEqual([])
    expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '確定' })).toBeDisabled()
  })

  it('表示した数の駒を用意する', () => {
    render(<App />)
    prepare('5', '3')
    expect(within(unplaced()).getAllByRole('button')).toHaveLength(8)
    expect(token('味方5')).toBeVisible()
    expect(token('敵3')).toBeVisible()
  })

  it('双方10体の20体を色と番号で見分け、10を0と省略しない', () => {
    render(<App />)
    prepare('10', '10')
    expect(within(unplaced()).getAllByRole('button').map((button) => button.getAttribute('aria-label'))).toEqual(
      ['味方', '敵'].flatMap((side) => Array.from({ length: 10 }, (_, i) => `未配置 ${side}${i + 1}（${side}・移動力5）`)),
    )
    for (const side of ['味方', '敵']) {
      for (let number = 1; number <= 10; number += 1) {
        expect(token(`${side}${number}`)).toHaveAccessibleName(`未配置 ${side}${number}（${side}・移動力5）`)
      }
    }
    place('味方10', 1, 1)
    place('敵10', 10, 10)
    expect(within(cell(1, 1)).getByText('10')).toBeVisible()
    expect(within(cell(10, 10)).getByText('10')).toBeVisible()
    expect(cell(1, 1).querySelector('span')).toHaveClass('board-token-ally')
    expect(cell(10, 10).querySelector('span')).toHaveClass('board-token-enemy')
  })
})

describe('未配置から配置・確定・移動まで', () => {
  it('未配置/配置済みの全組合せで選択だけ切替し、同じ駒で解除、配置後は選択が残らない', () => {
    render(<App />)
    prepare()
    fireEvent.click(cell(2, 2))
    fireEvent.click(token('味方1'))
    expect(pressed()).toEqual([token('味方1')])
    expect(range()).toEqual([])
    fireEvent.click(token('味方1'))
    expect(pressed()).toEqual([])
    fireEvent.click(token('味方1'))
    fireEvent.click(token('敵1'))
    expect(pressed()).toEqual([token('敵1')])
    expect(within(unplaced()).getAllByRole('button')).toHaveLength(3)
    fireEvent.click(cell(4, 4))
    expect(occupants()).toEqual(['マス (4, 4) 敵1（敵・移動力5）'])
    expect(within(unplaced()).getAllByRole('button')).toHaveLength(2)
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
    fireEvent.click(token('味方1'))
    fireEvent.click(cell(4, 4)) // 未配置→配置済み: 配置せず選択だけ切替
    expect(pressed()).toEqual([cell(4, 4)])
    expect(occupants()).toHaveLength(1)
    expect(within(unplaced()).getAllByRole('button')).toHaveLength(2)
    fireEvent.click(token('味方2')) // 配置済み→未配置: 移動しない
    expect(pressed()).toEqual([token('味方2')])
    expect(range()).toEqual([])
    expect(occupants()).toEqual(['マス (4, 4) 敵1（敵・移動力5）'])
    fireEvent.click(cell(3, 4))
    fireEvent.click(cell(3, 4))
    fireEvent.click(cell(4, 4)) // 配置済み→配置済み
    expect(pressed()).toEqual([cell(4, 4)])
    expect(occupants()).toHaveLength(2)
    fireEvent.click(cell(4, 4))
    expect(pressed()).toEqual([])
    fireEvent.click(cell(1, 1)) // 配置後に残った選択による二重配置を防ぐ
    expect(pressed()).toEqual([cell(1, 1)])
    expect(occupants()).toHaveLength(2)
  })

  it('移動力は全駒5、距離境界と占有を示し、準備中にも範囲外へ移動する', () => {
    render(<App />)
    prepare('1', '1')
    place('味方1', 1, 1)
    place('敵1', 2, 1)
    fireEvent.click(cell(1, 1))
    expect(cell(6, 1)).toHaveAccessibleName('マス (6, 1) 移動範囲')
    expect(cell(7, 1)).toHaveAccessibleName('マス (7, 1)')
    expect(cell(4, 4)).toHaveAccessibleName('マス (4, 4) 移動範囲')
    expect(cell(5, 5)).toHaveAccessibleName('マス (5, 5)')
    expect(cell(2, 1)).toHaveAccessibleName('マス (2, 1) 敵1（敵・移動力5）')
    fireEvent.click(cell(6, 1))
    expect(cell(6, 1)).toHaveAccessibleName('マス (6, 1) 味方1（味方・移動力5）')
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
    fireEvent.click(cell(6, 1))
    fireEvent.click(cell(10, 10))
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 味方1（味方・移動力5）')
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
  })

  it.each(['駒', 'マス'])('全配置だけでは確定せず、確定時は%sの選択と範囲を解除して配置を引き継ぐ', (selected) => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 3, 4)
    expect(screen.getByRole('button', { name: '確定' })).toBeEnabled()
    expect(screen.getByText('全駒を配置しました。「確定」で準備を完了します。')).toBeVisible()
    expect(screen.queryByRole('button', { name: '新しい戦闘を始める' })).not.toBeInTheDocument()
    fireEvent.click(selected === '駒' ? cell(3, 4) : cell(1, 1))
    expect(pressed()).toHaveLength(1)
    click('確定')
    expect(pressed()).toEqual([])
    expect(range()).toEqual([])
    expect(cell(3, 4)).toHaveAccessibleName('マス (3, 4) 味方1（味方・移動力5）')
    expect(screen.queryByRole('button', { name: '確定' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: '準備をやり直す' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '新しい戦闘を始める' })).toBeVisible()
    expect(screen.getByRole('region', { name: '戦闘中' })).toBeVisible()
    expect(screen.getByRole('heading', { name: '準備完了' })).toBeVisible()
    fireEvent.click(cell(3, 4))
    expect(range().length).toBeGreaterThan(0)
    fireEvent.click(cell(10, 10))
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 味方1（味方・移動力5）')
  })
})

describe('確認付きの全体やり直し', () => {
  it('確認の両端でTabとShift+Tabを押すと確認内に戻り、他のキーでは選択や段階を変えない', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 3, 4)
    click('準備をやり直す')
    const dialog = screen.getByRole('dialog')
    const cancel = within(dialog).getByRole('button', { name: 'キャンセル' })
    const approve = within(dialog).getByRole('button', { name: 'やり直す' })
    const key = (target: HTMLElement, name: string, shiftKey: boolean, prevented: boolean) => {
      const event = new KeyboardEvent('keydown', { key: name, shiftKey, bubbles: true, cancelable: true })
      fireEvent(target, event)
      expect(event.defaultPrevented).toBe(prevented)
    }
    expect(cancel).toHaveFocus()
    key(cancel, 'ArrowLeft', false, false)
    expect(cancel).toHaveFocus()
    // 内側への移動はブラウザへ渡し、両端から循環させるときだけ既定の移動を止める。
    key(cancel, 'Tab', false, false)
    key(cancel, 'Tab', true, true)
    expect(approve).toHaveFocus()
    key(approve, 'ArrowLeft', false, false)
    expect(approve).toHaveFocus()
    key(approve, 'Tab', true, false)
    key(approve, 'Tab', false, true)
    expect(cancel).toHaveFocus()
    click('キャンセル')
    expect(screen.getByRole('button', { name: '準備をやり直す' })).toHaveFocus()
    expect(screen.getByRole('region', { name: '配置の準備' })).toBeVisible()
    expect(cell(3, 4)).toHaveAccessibleName('マス (3, 4) 味方1（味方・移動力5）')
  })

  it.each(['準備中', '確定後'])('%sでEscの取消イベントを受けると段階・選択・位置を維持して開いたボタンへ戻す', (phase) => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 3, 4)
    if (phase === '確定後') click('確定')
    fireEvent.click(cell(3, 4))
    const before = { occupied: occupants(), selected: pressed(), range: range() }
    const opener = screen.getByRole('button', { name: phase === '準備中' ? '準備をやり直す' : '新しい戦闘を始める' })
    opener.focus()
    fireEvent.click(opener)
    const dialog = screen.getByRole('dialog')
    fireEvent(dialog, new Event('cancel', { cancelable: true }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(opener).toHaveFocus()
    expect(occupants()).toEqual(before.occupied)
    expect(pressed()).toEqual(before.selected)
    expect(range()).toEqual(before.range)
    expect(screen.getByRole('region', { name: phase === '準備中' ? '配置の準備' : '戦闘中' })).toBeVisible()
  })

  it.each(['未配置', '配置済み', 'マス'])('準備中の確認取消で%sの選択を含め全内容を保ち、承認すると0/0に戻る', (selected) => {
    render(<App />)
    prepare()
    place('味方1', 3, 4)
    fireEvent.click(selected === '未配置' ? token('敵1') : selected === '配置済み' ? cell(3, 4) : cell(1, 1))
    const before = { occupied: occupants(), selected: pressed(), range: range(), unplaced: within(unplaced()).getAllByRole('button') }
    const opener = screen.getByRole('button', { name: '準備をやり直す' })
    opener.focus()
    fireEvent.click(opener)
    const dialog = screen.getByRole('dialog', { name: '準備をやり直す' })
    expect(dialog).toHaveAccessibleDescription('今の戦闘の準備を最初からやり直します。未配置・配置済みの全駒と、味方・敵の数の設定を消して、最初の準備画面へ戻ります。')
    expect(within(dialog).getByRole('button', { name: 'キャンセル' })).toHaveFocus()
    click('キャンセル')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(opener).toHaveFocus()
    expect(occupants()).toEqual(before.occupied)
    expect(pressed()).toEqual(before.selected)
    expect(range()).toEqual(before.range)
    expect(within(unplaced()).getAllByRole('button')).toEqual(before.unplaced)
    expect(screen.getByRole('button', { name: '確定' })).toBeDisabled()
    click('準備をやり直す')
    click('やり直す')
    expectInitial()
    expect(document.body).toHaveFocus()
    prepare('0', '1')
    expect(token('敵1')).toBeVisible()
  })

  it('新しい戦闘の確認を取り消すと確定後を維持し、承認後は改めて準備・確定できる', () => {
    render(<App />)
    prepare('0', '1')
    place('敵1', 5, 5)
    click('確定')
    fireEvent.click(cell(5, 5))
    const before = { occupied: occupants(), selected: pressed(), range: range() }
    const opener = screen.getByRole('button', { name: '新しい戦闘を始める' })
    opener.focus()
    fireEvent.click(opener)
    const dialog = screen.getByRole('dialog', { name: '新しい戦闘を始める' })
    expect(dialog).toHaveAccessibleDescription('次の戦闘の準備をゼロから始めます。今の盤面の全駒と、味方・敵の数の設定を消して、最初の準備画面へ戻ります。')
    expect(within(dialog).getByRole('button', { name: 'キャンセル' })).toHaveFocus()
    click('キャンセル')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(opener).toHaveFocus()
    expect(occupants()).toEqual(before.occupied)
    expect(pressed()).toEqual(before.selected)
    expect(range()).toEqual(before.range)
    expect(screen.getByRole('button', { name: '新しい戦闘を始める' })).toBeVisible()
    click('新しい戦闘を始める')
    click('始める')
    expectInitial()
    expect(document.body).toHaveFocus()
    prepare('1', '0')
    place('味方1', 1, 1)
    click('確定')
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5）')
    expect(screen.getByRole('button', { name: '新しい戦闘を始める' })).toBeVisible()
  })
})

it('入力フォームの送信では画面遷移を防ぎ、指定した駒を用意する', () => {
  render(<App />)
  input('味方', '1')
  const form = field('味方').closest('form')!
  const submit = new Event('submit', { bubbles: true, cancelable: true })
  fireEvent(form, submit)
  expect(submit.defaultPrevented).toBe(true)
  expect(token('味方1')).toBeVisible()
})
