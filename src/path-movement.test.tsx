import { fireEvent, render, screen, within } from '@testing-library/react'
import App from './App.tsx'
import { setCount } from './test/counts.ts'

const cell = (x: number, y: number) => screen.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const click = (name: string) => fireEvent.click(screen.getByRole('button', { name }))
const select = (x: number, y: number) => fireEvent.click(cell(x, y))
const range = () => screen.queryAllByRole('button', { name: / 移動範囲$/ })
const noSelection = () => {
  expect(screen.queryAllByRole('button', { pressed: true })).toEqual([])
  expect(range()).toEqual([])
}
function place(name: string, x: number, y: number) {
  fireEvent.click(screen.getByRole('button', { name: new RegExp(`^未配置 ${name}（`) }))
  expect(range()).toEqual([])
  select(x, y)
  noSelection()
}
function movement(name: string, value: number) {
  click('設定')
  const group = within(screen.getByRole('group', { name: `${name}の移動力` }))
  const current = Number(group.getByRole('status').textContent)
  for (let n = current; n !== value; n += n < value ? 1 : -1) {
    click(`${name}の移動力を${n < value ? '増やす' : '減らす'}`)
  }
  expect(group.getByRole('status')).toHaveTextContent(String(value))
  click('閉じる')
}
function toggleDowned() {
  click('設定')
  const button = screen.queryByRole('button', { name: '倒れた状態にする' })
    ?? screen.getByRole('button', { name: '通常に戻す' })
  fireEvent.click(button)
  click('閉じる')
}
function prepare(ally: number, enemy: number) {
  render(<App />)
  setCount('味方の数', ally)
  setCount('敵の数', enemy)
  click('駒を用意する')
}

describe('他の駒を避ける目安と盤面操作（#60）', () => {
  it.each(['味方2', '敵1'])('準備中は%sも壁になり、状態と移動力の変更を現在の目安に反映する', (obstacle) => {
    prepare(2, 1)
    place('味方1', 1, 2)
    place(obstacle, 2, 2)
    select(1, 2)
    movement('味方1', 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2)')
    expect(cell(2, 1)).toHaveAccessibleName('マス (2, 1) 移動範囲')
    movement('味方1', 3)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2) 移動範囲')
    movement('味方1', 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2)')

    // 占有マスを押しても移動せず、その駒を選ぶ。倒れた駒自身の目安は出ない。
    select(2, 2)
    expect(cell(1, 2)).toHaveAccessibleName('マス (1, 2) 味方1（味方・移動力2）')
    expect(cell(2, 2)).toHaveAttribute('aria-pressed', 'true')
    toggleDowned()
    expect(range()).toEqual([])
    select(1, 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2) 移動範囲')
    expect(cell(2, 2)).not.toHaveClass('board-cell-range')
    select(2, 2)
    toggleDowned()
    select(1, 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2)')
    // 未配置の残り1体は通り道を塞がない。
    expect(cell(1, 4)).toHaveAccessibleName('マス (1, 4) 移動範囲')
  })

  it('斜めの両脇が通常なら囲われ、片方を倒すと通れ、範囲外でも自由に移動できる', () => {
    prepare(2, 1)
    place('味方1', 1, 1)
    place('味方2', 2, 1)
    place('敵1', 1, 2)
    select(1, 1)
    movement('味方1', 1)
    expect(range()).toEqual([])
    click('確定')
    select(1, 1)
    expect(range()).toEqual([])
    select(1, 2)
    toggleDowned()
    select(1, 1)
    expect(range()).toEqual([cell(2, 2)])
    select(1, 2)
    // 倒れた駒は動かず、空きマスの選択へ切り替わる。
    select(3, 3)
    expect(cell(1, 2)).toHaveAccessibleName('マス (1, 2) 敵1（敵・移動力5・倒れた状態）')
    expect(cell(3, 3)).toHaveAttribute('aria-pressed', 'true')
    expect(range()).toEqual([])
    select(1, 2)
    toggleDowned()
    select(1, 1)
    expect(range()).toEqual([])
    select(2, 2)
    expect(cell(2, 2)).toHaveAccessibleName('マス (2, 2) 味方1（味方・移動力1）')
    noSelection()
    select(2, 2)
    expect(range().length).toBeGreaterThan(0)
    select(10, 10)
    expect(cell(10, 10)).toHaveAccessibleName('マス (10, 10) 味方1（味方・移動力1）')
    noSelection()
  })

  it('配置・移動・削除・途中追加と追加分確定の後も現在の配置で再計算する', () => {
    prepare(1, 1)
    place('味方1', 1, 2)
    select(1, 2)
    movement('味方1', 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2) 移動範囲')
    place('敵1', 2, 2)
    select(1, 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2)')
    click('確定')
    select(2, 2)
    select(10, 10)
    select(1, 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2) 移動範囲')

    click('駒を増やす')
    setCount('敵の追加数', 1)
    click('追加する')
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2) 移動範囲')
    place('敵2', 2, 2)
    select(2, 2)
    movement('敵2', 2)
    expect(cell(1, 2)).not.toHaveClass('board-cell-range')
    expect(cell(1, 3)).toHaveClass('board-cell-range')
    select(1, 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2)')
    click('追加分を確定')
    select(1, 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2)')
    select(2, 2)
    click('設定')
    click('この駒を削除')
    click('削除する')
    noSelection()
    select(1, 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2) 移動範囲')
  })

  it('未配置の倒れた駒は目安を出さず初回配置でき、配置後は通過だけできる', () => {
    prepare(1, 1)
    place('味方1', 1, 2)
    select(1, 2)
    movement('味方1', 2)
    fireEvent.click(screen.getByRole('button', { name: /^未配置 敵1（/ }))
    toggleDowned()
    expect(range()).toEqual([])
    select(2, 2)
    noSelection()
    select(2, 2)
    expect(range()).toEqual([])
    select(1, 2)
    expect(cell(3, 2)).toHaveAccessibleName('マス (3, 2) 移動範囲')
    expect(cell(2, 2)).not.toHaveClass('board-cell-range')
  })
})
