import { act, fireEvent, render, screen } from '@testing-library/react'
import App from './App.tsx'
import { setCount } from './test/counts.ts'

const cell = (x = 1, y = 1) => screen.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const click = (name: string) => fireEvent.click(screen.getByRole('button', { name, exact: true }))
const viewport = () => screen.getByRole('group', { name: '盤面の表示領域' })
const transform = () => screen.getByRole('group', { name: '戦闘盤面' }).parentElement!.style.transform
const zoom = (deltaY = -Math.log(2) / 0.002) => fireEvent.wheel(viewport(), { deltaY, clientX: 150, clientY: 150 })
const pointer = (target: HTMLElement, type: 'pointerDown' | 'pointerMove' | 'pointerUp' | 'pointerCancel',
  x: number, y: number, pointerType = 'mouse', button = 0, pointerId = 1) =>
  fireEvent[type](target, { pointerId, pointerType, button, clientX: x, clientY: y })
function prepare() {
  setCount('味方の数', 1)
  click('駒を用意する')
  fireEvent.click(screen.getByRole('button', { name: /^未配置 味方1/ }))
  fireEvent.click(cell())
}

beforeEach(() => {
  // jsdomのレイアウト境界のみ補う。ヒット判定・pointer capture・実寸法はChromiumで確認する。
  const original = HTMLElement.prototype.getBoundingClientRect
  vi.spyOn(HTMLElement.prototype, 'getBoundingClientRect').mockImplementation(function (this: HTMLElement) {
    return this.classList.contains('board-viewport')
      ? DOMRect.fromRect({ x: 0, y: 0, width: 300, height: 300 }) : original.call(this)
  })
})
afterEach(() => { vi.restoreAllMocks(); vi.useRealTimers() })

it('最初は全体。ホイールは上下限でもページへ流さず、全体を見るで表示だけ戻す', () => {
  render(<App />)
  prepare()
  fireEvent.click(cell())
  expect(screen.getByText('倍率 1.0倍')).toBeVisible()
  expect(viewport()).toHaveStyle({ touchAction: 'pan-y' })
  expect(zoom()).toBe(false)
  expect(screen.getByText('倍率 2.0倍')).toBeVisible()
  expect(viewport()).toHaveStyle({ touchAction: 'none' })
  expect(transform()).toBe('translate(-150px, -150px) scale(2)')
  expect(zoom(-10000)).toBe(false)
  expect(screen.getByText('倍率 4.0倍')).toBeVisible()
  expect(zoom(-100)).toBe(false)
  click('全体を見る')
  expect(screen.getByText('倍率 1.0倍')).toBeVisible()
  expect(transform()).toBe('translate(0px, 0px) scale(1)')
  expect(cell()).toHaveAttribute('aria-pressed', 'true')
  expect(cell()).toHaveAccessibleName(/味方1/)
  expect(screen.getAllByRole('button', { name: /移動範囲$/ }).length).toBeGreaterThan(0)
  expect(zoom(1000)).toBe(false)
  expect(screen.getByText('倍率 1.0倍')).toBeVisible()
})

it.each([['mouse', 0], ['mouse', 2], ['touch', 0]] as const)('%s・ボタン%sで駒からドラッグしても表示だけ動き、終わりのclickで選択解除・移動・設定をしない', (kind, button) => {
  vi.useFakeTimers()
  render(<App />)
  prepare()
  fireEvent.click(cell())
  zoom()
  pointer(cell(), 'pointerDown', 100, 100, kind, button)
  pointer(cell(), 'pointerMove', 140, 125, kind, button)
  act(() => { vi.advanceTimersByTime(800) })
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  pointer(viewport(), 'pointerUp', 140, 125, kind, button)
  fireEvent.click(cell(2, 2), { detail: 1 })
  expect(transform()).toBe('translate(-110px, -125px) scale(2)')
  expect(cell()).toHaveAttribute('aria-pressed', 'true')
  expect(cell()).toHaveAccessibleName(/味方1/)
  expect(cell(2, 2)).not.toHaveAccessibleName(/味方1/)
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  // 次の実際の押下は再び通常の選択・移動として使える。
  pointer(cell(2, 2), 'pointerDown', 150, 150, kind)
  pointer(cell(2, 2), 'pointerUp', 150, 150, kind)
  fireEvent.click(cell(2, 2), { detail: 1 })
  expect(cell(2, 2)).toHaveAccessibleName(/味方1/)
})

it('二本目の指が入るだけで長押しを取り消し、中点と距離でピンチし、一本に戻ってもドラッグを継続する', () => {
  vi.useFakeTimers()
  render(<App />)
  prepare()
  pointer(cell(), 'pointerDown', 100, 150, 'touch')
  act(() => { vi.advanceTimersByTime(300) })
  pointer(cell(2, 2), 'pointerDown', 200, 150, 'touch', 0, 2)
  act(() => { vi.advanceTimersByTime(800) })
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  pointer(viewport(), 'pointerMove', 250, 150, 'touch', 0, 2)
  expect(screen.getByText('倍率 1.5倍')).toBeVisible()
  pointer(viewport(), 'pointerMove', 50, 150, 'touch')
  expect(screen.getByText('倍率 2.0倍')).toBeVisible()
  pointer(viewport(), 'pointerUp', 250, 150, 'touch', 0, 2)
  pointer(viewport(), 'pointerMove', 70, 160, 'touch')
  expect(transform()).toBe('translate(-130px, -140px) scale(2)')
  pointer(viewport(), 'pointerUp', 70, 160, 'touch')
  fireEvent.click(cell(), { detail: 1 })
  expect(cell()).toHaveAttribute('aria-pressed', 'false')
  expect(cell()).toHaveAccessibleName(/味方1/)
})

it('右押下や押下中のcontextmenuでは開かず、静止して離すと開く。右ドラッグのcontextmenuは開かない', () => {
  render(<App />)
  prepare()
  pointer(cell(), 'pointerDown', 100, 100, 'mouse', 2)
  expect(fireEvent.contextMenu(cell(), { button: 2 })).toBe(false)
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  pointer(cell(), 'pointerUp', 100, 100, 'mouse', 2)
  expect(screen.getByRole('dialog', { name: '味方1の設定' })).toBeVisible()
  click('閉じる')
  pointer(cell(), 'pointerDown', 100, 100, 'mouse', 2)
  pointer(cell(), 'pointerMove', 120, 100, 'mouse', 2)
  pointer(viewport(), 'pointerUp', 120, 100, 'mouse', 2)
  fireEvent.contextMenu(cell(), { button: 2 })
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
})

it.each(['ContextMenu', 'F10'])('キーボードの%sから設定を開ける。ドラッグ後もEnterのclickは通常の選択に使える', (key) => {
  render(<App />)
  prepare()
  pointer(cell(), 'pointerDown', 100, 100)
  pointer(cell(), 'pointerMove', 120, 100)
  pointer(viewport(), 'pointerUp', 120, 100)
  fireEvent.click(cell(), { detail: 0 })
  expect(cell()).toHaveAttribute('aria-pressed', 'true')
  fireEvent.keyDown(cell(), { key, shiftKey: key === 'F10' })
  expect(screen.getByRole('dialog', { name: '味方1の設定' })).toBeVisible()
})

it('10pxまでのタップは維持し、キャンセル後とホイール開始後は長押しで開かない', () => {
  vi.useFakeTimers()
  render(<App />)
  prepare()
  pointer(cell(), 'pointerDown', 100, 100, 'touch')
  pointer(cell(), 'pointerMove', 106, 108, 'touch')
  pointer(cell(), 'pointerUp', 106, 108, 'touch')
  fireEvent.click(cell(), { detail: 1 })
  expect(cell()).toHaveAttribute('aria-pressed', 'true')
  pointer(cell(), 'pointerDown', 100, 100, 'touch')
  pointer(cell(), 'pointerCancel', 100, 100, 'touch')
  act(() => { vi.advanceTimersByTime(600) })
  fireEvent.click(cell(2, 2), { detail: 1 })
  expect(cell()).toHaveAttribute('aria-pressed', 'true')
  pointer(cell(), 'pointerDown', 100, 100, 'touch')
  zoom()
  act(() => { vi.advanceTimersByTime(600) })
  pointer(cell(), 'pointerUp', 100, 100, 'touch')
  fireEvent.click(cell(), { detail: 1 })
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(cell()).toHaveAttribute('aria-pressed', 'true')
})

it('配置・確定・状態変更では倍率を保ち、全体を見るは倒れた状態を保ち、戦闘のリセットだけで全体に戻る', () => {
  render(<App />)
  zoom()
  prepare()
  expect(screen.getByText('倍率 2.0倍')).toBeVisible()
  click('確定')
  fireEvent.click(cell())
  click('設定')
  click('倒れた状態にする')
  click('閉じる')
  expect(screen.getByText('倍率 2.0倍')).toBeVisible()
  fireEvent.click(cell(2, 2))
  expect(cell()).toHaveAccessibleName(/倒れた状態/)
  expect(cell(2, 2)).toHaveAttribute('aria-pressed', 'true')
  click('全体を見る')
  expect(cell()).toHaveAccessibleName(/倒れた状態/)
  expect(cell(2, 2)).toHaveAttribute('aria-pressed', 'true')
  zoom()
  click('新しい戦闘を始める')
  click('始める')
  expect(screen.getByText('倍率 1.0倍')).toBeVisible()
  prepare()
  zoom()
  click('準備をやり直す')
  click('やり直す')
  expect(screen.getByText('倍率 1.0倍')).toBeVisible()
})
