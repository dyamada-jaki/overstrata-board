import { act, fireEvent, render, screen, within } from '@testing-library/react'
import App from './App.tsx'

const click = (name: string | RegExp) => fireEvent.click(screen.getByRole('button', { name }))
const cell = (x: number, y: number) => screen.getByRole('button', { name: new RegExp(`^マス \\(${x}, ${y}\\)`) })
const token = (name: string) => screen.getByRole('button', { name: new RegExp(`(?:^未配置 | )${name}（`) })
const input = (name: string, value: string) => fireEvent.change(screen.getByRole('textbox', { name }), { target: { value } })
const pressed = () => screen.queryAllByRole('button', { pressed: true })
const range = () => screen.queryAllByRole('button', { name: / 移動範囲$/ })
const settingsButton = () => screen.getByRole('button', { name: '設定' })
const popup = (name: string) => screen.getByRole('dialog', { name: `${name}の設定` })
const popups = () => screen.queryAllByRole('dialog', { name: /の設定$/ })
const inPopup = (name: string) => within(popup(name))
const guidance = '味方か敵を1体以上にしてください'
function prepare(ally: string, enemy: string) {
  input('味方の数', ally)
  input('敵の数', enemy)
  click('駒を用意する')
}
function place(name: string, x: number, y: number) {
  fireEvent.click(token(name))
  fireEvent.click(cell(x, y))
}
/** 背後の操作の前に、外側（backdrop = dialog 要素そのもの）を押して閉じる。 */
function tapOutside(name: string) {
  const dialog = popup(name)
  fireEvent.pointerDown(dialog, { pointerType: 'mouse' })
  fireEvent.click(dialog, { detail: 1 })
}
const touch = (element: HTMLElement, type: 'pointerDown' | 'pointerMove' | 'pointerUp' | 'pointerCancel', x = 10, y = 10) =>
  fireEvent[type](element, { pointerType: 'touch', pointerId: 1, clientX: x, clientY: y })

describe('数の案内の表示領域（#45 場面1）', () => {
  it('開始画面で0→1にしても案内の要素を残して文だけ隠し、0に戻すと再び見せる', () => {
    render(<App />)
    const text = screen.getByText(guidance)
    expect(text).toBeVisible()
    click('味方の数を増やす')
    expect(screen.getByText(guidance)).toBe(text)
    expect(text).not.toBeVisible()
    click('味方の数を増やす')
    expect(text).not.toBeVisible()
    click('味方の数を減らす')
    click('味方の数を減らす')
    expect(text).toBeVisible()
  })

  it('追加数のエリアでも0→1で案内の要素を残して文だけ隠す（受け入れ条件8でPOと確定）', () => {
    render(<App />)
    prepare('0', '1')
    click('駒を増やす')
    const form = screen.getByRole('group', { name: '駒の追加数' })
    const text = within(form).getByText(guidance)
    expect(text).toBeVisible()
    click('敵の追加数を増やす')
    expect(within(form).getByText(guidance)).toBe(text)
    expect(text).not.toBeVisible()
    click('敵の追加数を減らす')
    expect(text).toBeVisible()
  })
})

describe('通常の選択では設定を開かない（#45 場面2）', () => {
  it('選択・解除・切り替えでポップアップも設定欄も出さず、「設定」は常に表示して未選択では押せない', () => {
    render(<App />)
    prepare('2', '1')
    expect(settingsButton()).toBeDisabled()
    expect(screen.getByText('選択中：なし')).toBeVisible()
    fireEvent.click(token('味方1'))
    expect(popups()).toEqual([])
    expect(screen.queryAllByRole('group', { name: /の移動力$/ })).toEqual([])
    expect(screen.queryByRole('button', { name: /^(倒れた状態にする|通常に戻す|この駒を削除)$/ })).not.toBeInTheDocument()
    expect(settingsButton()).toBeEnabled()
    expect(screen.getByText(/^選択中：/)).toHaveTextContent('選択中：1味方1')
    fireEvent.click(token('敵1'))
    expect(popups()).toEqual([])
    expect(screen.getByText(/^選択中：/)).toHaveTextContent('選択中：1敵1')
    fireEvent.click(token('敵1'))
    expect(settingsButton()).toBeDisabled()
    expect(screen.getByText('選択中：なし')).toBeVisible()
    place('味方1', 1, 1)
    fireEvent.click(cell(1, 1))
    expect(popups()).toEqual([])
    expect(settingsButton()).toBeEnabled()
    fireEvent.click(cell(1, 1))
    expect(settingsButton()).toBeDisabled()
  })
})

describe('右クリック・「設定」で開く（#45）', () => {
  it('右クリックした未配置の駒を選択して開き、駒名・陣営・番号で対象を示す。既定のメニューは止める', () => {
    render(<App />)
    prepare('2', '1')
    expect(fireEvent.contextMenu(token('味方2'))).toBe(false)
    expect(token('味方2')).toHaveAttribute('aria-pressed', 'true')
    expect(pressed()).toEqual([token('味方2')])
    const heading = inPopup('味方2').getByRole('heading', { name: '味方2の設定' })
    expect(heading.querySelector('.board-token')).toHaveClass('board-token-ally')
    expect(heading).toHaveTextContent('2味方2の設定')
  })

  it('選択中の同じ駒は選択を保って開き、別の駒を選択中なら選択だけを切り替える。どの駒も動かない', () => {
    render(<App />)
    prepare('1', '1')
    place('敵1', 3, 3)
    fireEvent.click(token('味方1'))
    fireEvent.contextMenu(token('味方1'))
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'true')
    expect(popup('味方1')).toBeInTheDocument()
    click('閉じる')
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'true')
    fireEvent.contextMenu(cell(3, 3))
    expect(popup('敵1')).toBeInTheDocument()
    expect(pressed()).toEqual([cell(3, 3)])
    expect(cell(3, 3)).toHaveAccessibleName('マス (3, 3) 敵1（敵・移動力5）')
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'false')
  })

  it('空きマス・マス選択からの右クリックでは開かず、マス選択から駒への右クリックは駒を選ぶ', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    fireEvent.contextMenu(cell(5, 5))
    expect(popups()).toEqual([])
    fireEvent.click(cell(5, 5))
    expect(pressed()).toEqual([cell(5, 5)])
    fireEvent.contextMenu(cell(1, 1))
    expect(popup('味方1')).toBeInTheDocument()
    expect(pressed()).toEqual([cell(1, 1)])
  })

  it('「設定」から選択中の駒の同じポップアップを開く', () => {
    render(<App />)
    prepare('1', '1')
    place('敵1', 2, 2)
    fireEvent.click(cell(2, 2))
    click('設定')
    expect(popup('敵1')).toBeInTheDocument()
    expect(inPopup('敵1').getByRole('group', { name: '敵1の移動力' })).toBeInTheDocument()
    expect(pressed()).toEqual([cell(2, 2)])
  })
})

describe('長押しで開く（#45。時刻だけ偽のタイマーにする）', () => {
  beforeEach(() => { vi.useFakeTimers() })
  afterEach(() => { vi.useRealTimers() })

  it('タッチで499msでは開かず、500msで選択して開く。指を離した後の click で選択を解除しない', () => {
    render(<App />)
    prepare('1', '0')
    touch(token('味方1'), 'pointerDown')
    act(() => { vi.advanceTimersByTime(499) })
    expect(popups()).toEqual([])
    act(() => { vi.advanceTimersByTime(1) })
    expect(popup('味方1')).toBeInTheDocument()
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'true')
    touch(token('味方1'), 'pointerUp')
    fireEvent.click(token('味方1'), { detail: 1 })
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'true')
    expect(popup('味方1')).toBeInTheDocument()
  })

  it('500ms前に指を離せば通常のタップとして選択し、開かない', () => {
    render(<App />)
    prepare('1', '0')
    touch(token('味方1'), 'pointerDown')
    act(() => { vi.advanceTimersByTime(300) })
    touch(token('味方1'), 'pointerUp')
    fireEvent.click(token('味方1'), { detail: 1 })
    act(() => { vi.advanceTimersByTime(1000) })
    expect(popups()).toEqual([])
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'true')
  })

  it('配置済みの駒も長押しで開き、10pxまでの指の揺れは許すが、11px動かすと取り消す', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    touch(cell(1, 1), 'pointerDown', 100, 100)
    touch(cell(1, 1), 'pointerMove', 106, 108)
    act(() => { vi.advanceTimersByTime(500) })
    expect(popup('味方1')).toBeInTheDocument()
    click('閉じる')
    touch(cell(1, 1), 'pointerDown', 100, 100)
    touch(cell(1, 1), 'pointerMove', 100, 111)
    act(() => { vi.advanceTimersByTime(1000) })
    expect(popups()).toEqual([])
  })

  it('スクロールの開始（pointercancel・scroll）で取り消す。マウスの左ボタンの長押しでは開かない', () => {
    render(<App />)
    prepare('1', '0')
    touch(token('味方1'), 'pointerDown')
    touch(token('味方1'), 'pointerCancel')
    act(() => { vi.advanceTimersByTime(1000) })
    expect(popups()).toEqual([])
    touch(token('味方1'), 'pointerDown')
    fireEvent.scroll(window)
    act(() => { vi.advanceTimersByTime(1000) })
    expect(popups()).toEqual([])
    fireEvent.pointerDown(token('味方1'), { pointerType: 'mouse', pointerId: 1 })
    act(() => { vi.advanceTimersByTime(1000) })
    expect(popups()).toEqual([])
    expect(pressed()).toEqual([])
  })
})

describe('ポップアップの中身（#45。既存の条件を保つ）', () => {
  it('移動力は0〜9を1ずつ。0の−と9の＋は押せず、値は駒へすぐ反映する', () => {
    render(<App />)
    prepare('1', '0')
    fireEvent.contextMenu(token('味方1'))
    const minus = () => inPopup('味方1').getByRole('button', { name: '味方1の移動力を減らす' })
    const plus = () => inPopup('味方1').getByRole('button', { name: '味方1の移動力を増やす' })
    const value = () => inPopup('味方1').getByRole('status')
    expect(value()).toHaveTextContent(/^5$/)
    for (let i = 0; i < 5; i += 1) fireEvent.click(minus())
    expect(value()).toHaveTextContent(/^0$/)
    expect(minus()).toBeDisabled()
    for (let i = 0; i < 9; i += 1) fireEvent.click(plus())
    expect(value()).toHaveTextContent(/^9$/)
    expect(plus()).toBeDisabled()
    expect(token('味方1')).toHaveAccessibleName('未配置 味方1（味方・移動力9）')
  })

  it('確定済みの駒は移動力を表示だけし、変更の操作を出さない', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    click('確定')
    fireEvent.contextMenu(cell(1, 1))
    expect(inPopup('味方1').getByText('移動力：5マス')).toBeVisible()
    expect(inPopup('味方1').queryByRole('button', { name: /移動力を/ })).not.toBeInTheDocument()
  })

  it('状態を確認なしで切り替え、表示・アクセシブル名・範囲に反映する。選択とボタンのフォーカスは保つ', () => {
    render(<App />)
    prepare('1', '0')
    place('味方1', 1, 1)
    fireEvent.contextMenu(cell(1, 1))
    expect(range()).not.toEqual([])
    expect(inPopup('味方1').getByText('状態：通常')).toBeVisible()
    const toggle = inPopup('味方1').getByRole('button', { name: '倒れた状態にする' })
    toggle.focus()
    fireEvent.click(toggle)
    expect(toggle).toHaveTextContent('通常に戻す')
    expect(toggle).toHaveFocus()
    expect(inPopup('味方1').getByText('状態：倒れている')).toBeVisible()
    expect(cell(1, 1)).toHaveAccessibleName('マス (1, 1) 味方1（味方・移動力5・倒れた状態）')
    expect(range()).toEqual([])
    expect(pressed()).toEqual([cell(1, 1)])
    fireEvent.click(toggle)
    expect(range()).not.toEqual([])
  })

  it('削除の確認をキャンセルすると同じ駒のポップアップへ戻り、値と状態を変えない。実行すると選択なしで閉じる', () => {
    render(<App />)
    prepare('2', '0')
    fireEvent.contextMenu(token('味方2'))
    click('味方2の移動力を減らす')
    click('倒れた状態にする')
    click('この駒を削除')
    expect(popups()).toEqual([])
    const confirm = screen.getByRole('dialog', { name: '駒を削除' })
    expect(confirm).toHaveTextContent('味方2を削除しますか？')
    fireEvent.click(within(confirm).getByRole('button', { name: 'キャンセル' }))
    expect(popup('味方2')).toBeInTheDocument()
    expect(inPopup('味方2').getByRole('button', { name: 'この駒を削除' })).toHaveFocus()
    expect(inPopup('味方2').getByRole('status')).toHaveTextContent(/^4$/)
    expect(inPopup('味方2').getByText('状態：倒れている')).toBeVisible()
    expect(token('味方2')).toHaveAttribute('aria-pressed', 'true')
    click('この駒を削除')
    fireEvent.click(within(screen.getByRole('dialog', { name: '駒を削除' })).getByRole('button', { name: '削除する' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /^未配置 味方2（/ })).not.toBeInTheDocument()
    expect(pressed()).toEqual([])
    expect(settingsButton()).toBeDisabled()
    expect(document.body).toHaveFocus()
  })
})

describe('閉じ方とフォーカス（#45）', () => {
  it('開くと「×」にフォーカスし、×・Escで閉じて選択を保ち、開いた元へフォーカスを戻す', () => {
    render(<App />)
    prepare('1', '0')
    fireEvent.click(token('味方1'))
    settingsButton().focus()
    click('設定')
    expect(inPopup('味方1').getByRole('button', { name: '閉じる' })).toHaveFocus()
    click('閉じる')
    expect(popups()).toEqual([])
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'true')
    expect(settingsButton()).toHaveFocus()
    fireEvent.contextMenu(token('味方1'))
    fireEvent(popup('味方1'), new Event('cancel', { cancelable: true }))
    expect(popups()).toEqual([])
    expect(token('味方1')).toHaveAttribute('aria-pressed', 'true')
    expect(token('味方1')).toHaveFocus()
  })

  it('Tab・Shift+Tabはポップアップ内を循環する', () => {
    render(<App />)
    prepare('1', '0')
    fireEvent.contextMenu(token('味方1'))
    const close = inPopup('味方1').getByRole('button', { name: '閉じる' })
    const remove = inPopup('味方1').getByRole('button', { name: 'この駒を削除' })
    fireEvent.keyDown(close, { key: 'Tab', shiftKey: true })
    expect(remove).toHaveFocus()
    fireEvent.keyDown(remove, { key: 'Tab' })
    expect(close).toHaveFocus()
  })

  it('外側は backdrop で押し始めて離したときだけ閉じ、選択・配置を変えない。開く操作から続く click では閉じない', () => {
    render(<App />)
    prepare('1', '1')
    place('味方1', 1, 1)
    fireEvent.contextMenu(cell(1, 1))
    fireEvent.click(popup('味方1'), { detail: 1 })
    expect(popup('味方1')).toBeInTheDocument()
    fireEvent.pointerDown(inPopup('味方1').getByText('状態：通常'), { pointerType: 'mouse' })
    fireEvent.click(popup('味方1'), { detail: 1 })
    expect(popup('味方1')).toBeInTheDocument()
    tapOutside('味方1')
    expect(popups()).toEqual([])
    expect(pressed()).toEqual([cell(1, 1)])
    expect(cell(1, 1)).toHaveAccessibleName(/^マス \(1, 1\) 味方1（/)
    expect(token('敵1')).toHaveAttribute('aria-pressed', 'false')
  })
})
